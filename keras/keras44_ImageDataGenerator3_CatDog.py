import numpy as np
import time
import datetime

# 이미지 파일을 폴더에서 읽어오고,
# 스케일링 / 데이터 증강 등을 설정할 수 있는 클래스
from tensorflow.keras.preprocessing.image import ImageDataGenerator

# Sequential:
# 레이어를 위에서 아래 순서대로 차례차례 쌓는 모델
from tensorflow.keras.models import Sequential

# Dense         : 완전연결층
# Conv2D        : 이미지의 특징을 추출하는 합성곱층
# Flatten       : 다차원 Feature Map을 1차원으로 펼침
# Dropout       : 학습 중 일부 뉴런의 출력을 랜덤하게 0으로 만들어 과적합 완화
# MaxPooling2D  : Feature Map의 가로/세로 크기를 줄이면서 주요 특징을 남김
from tensorflow.keras.layers import (
    Dense,
    Conv2D,
    Flatten,
    Dropout,
    MaxPooling2D
)

# EarlyStopping:
# 검증 성능이 더 이상 좋아지지 않을 때 학습을 조기에 종료
#
# ModelCheckpoint:
# 학습 도중 가장 좋은 성능을 기록한 모델을 파일로 저장
from tensorflow.keras.callbacks import EarlyStopping, ModelCheckpoint

# sklearn에서 제공하는 정확도 계산 함수
from sklearn.metrics import accuracy_score


# =============================================================================
# 1. 데이터 로드 - 개 / 고양이 이미지
# =============================================================================


# -----------------------------------------------------------------------------
# 전체 작업 시간 측정 시작
# -----------------------------------------------------------------------------

start_time = time.time()

# time.time()
# -> 현재 시간을 초 단위 숫자로 반환한다.
#
# 예:
#
# 1789958123.1234
#
# 나중에
#
# 종료시간 - 시작시간
#
# 을 계산하면 소요 시간을 구할 수 있다.


# =============================================================================
# ImageDataGenerator 생성
# =============================================================================

train_datagen = ImageDataGenerator(
    rescale=1./255
)

test_datagen = ImageDataGenerator(
    rescale=1./255
)

# 이미지 픽셀값은 일반적으로:
#
# 0 ~ 255
#
# 범위이다.
#
# rescale=1./255
#
# 는 모든 픽셀값에 1/255를 곱한다.
#
# 예:
#
# 0   -> 0.0
# 128 -> 약 0.502
# 255 -> 1.0
#
# 따라서:
#
# 0 ~ 255
#
#     ↓
#
# 0 ~ 1
#
# 범위로 스케일링된다.
#
#
# 현재 코드에는:
#
# horizontal_flip
# rotation_range
# zoom_range
#
# 등의 옵션이 없으므로
# Data Augmentation(데이터 증강)은 수행하지 않는다.
#
# 단순히 픽셀값만 0~1로 스케일링한다.


# =============================================================================
# 이미지 데이터가 저장되어 있는 경로
# =============================================================================

path_train = './_data/image/cat-dog/training_set/'
path_test = './_data/image/cat-dog/test_set/'


# 폴더 구조는 대략 다음과 같다고 보면 된다.
#
# cat-dog/
#
# ├── training_set/
# │   ├── cats/
# │   │   ├── cat.1.jpg
# │   │   ├── cat.2.jpg
# │   │   └── ...
# │   │
# │   └── dogs/
# │       ├── dog.1.jpg
# │       ├── dog.2.jpg
# │       └── ...
# │
# └── test_set/
#     ├── cats/
#     │   └── ...
#     │
#     └── dogs/
#         └── ...
#
#
# flow_from_directory()는
# 하위 폴더 이름을 보고 자동으로 class를 만든다.
#
# 예:
#
# cats/
# dogs/
#
# 가 있으면 일반적으로:
#
# cats -> 0
# dogs -> 1
#
# 과 같이 라벨을 생성한다.
#
# 정확한 라벨 번호는:
#
# print(train_data.class_indices)
#
# 로 확인하면 된다.


# =============================================================================
# 학습용 이미지 불러오기
# =============================================================================

train_data = train_datagen.flow_from_directory(

    # -------------------------------------------------------------------------
    # directory
    # -------------------------------------------------------------------------
    # 이미지가 들어있는 최상위 폴더
    path_train,


    # -------------------------------------------------------------------------
    # target_size=(100, 100)
    # -------------------------------------------------------------------------
    # 원본 이미지들의 크기가 서로 다르더라도
    # 모두 100 x 100으로 resize한다.
    #
    # 예:
    #
    # 300 x 200
    # 500 x 600
    # 1024 x 768
    #
    #         ↓
    #
    # 모두 100 x 100
    #
    # CNN의 입력 크기를 일정하게 맞추기 위해 필요하다.
    target_size=(100, 100),


    # -------------------------------------------------------------------------
    # batch_size=8005
    # -------------------------------------------------------------------------
    # DirectoryIterator가 한 번에 몇 장을 반환할 것인지 설정한다.
    #
    # 현재 학습 이미지가 총 8005장이고
    #
    # batch_size=8005
    #
    # 이므로 전체 이미지 8005장을 한 번에 가져온다.
    #
    # 따라서:
    #
    # train_data[0]
    #
    # 안에 전체 데이터가 들어가게 된다.
    #
    #
    # 일반적인 사용:
    #
    # batch_size=32
    #
    # 이미지 32장씩
    # ↓
    # 다음 32장
    # ↓
    # 다음 32장
    #
    #
    # 현재 코드:
    #
    # batch_size=8005
    #
    # 이미지 8005장 전부
    # ↓
    # RAM에 한 번에 올림
    #
    #
    # 따라서 메모리 사용량이 상당히 커질 수 있다.
    batch_size=8005,


    # -------------------------------------------------------------------------
    # class_mode='binary'
    # -------------------------------------------------------------------------
    # 두 개의 클래스를 구분하는 이진분류이다.
    #
    # 예:
    #
    # cats -> 0
    # dogs -> 1
    #
    # y 데이터:
    #
    # [0., 1., 0., 0., 1., ...]
    class_mode='binary',


    # -------------------------------------------------------------------------
    # color_mode='rgb'
    # -------------------------------------------------------------------------
    # 이미지를 RGB 컬러 이미지로 읽는다.
    #
    # 따라서 이미지 한 장의 shape:
    #
    # (100, 100, 3)
    #
    #                 ↑
    #                 RGB 3개 채널
    #
    # grayscale이었다면:
    #
    # (100, 100, 1)
    #
    # 이 되었을 것이다.
    color_mode='rgb',


    # -------------------------------------------------------------------------
    # shuffle=True
    # -------------------------------------------------------------------------
    # 학습 데이터 순서를 랜덤하게 섞는다.
    #
    # 예:
    #
    # 원래:
    # 1 2 3 4 5
    #
    # shuffle:
    # 4 1 5 2 3
    #
    # 모델이 데이터의 정렬 순서에 영향을 덜 받도록 하기 위해
    # 학습 데이터에서는 일반적으로 True를 사용한다.
    shuffle=True,
)


# =============================================================================
# 테스트용 이미지 불러오기
# =============================================================================

test_data = test_datagen.flow_from_directory(

    # 테스트 데이터가 들어있는 경로
    path_test,

    # 학습 데이터와 동일하게 100 x 100으로 resize
    target_size=(100, 100),

    # 테스트 이미지 전체가 2023장이므로
    # 한 번에 전체 데이터를 가져온다.
    batch_size=2023,

    # 개 / 고양이 이진분류
    class_mode='binary',

    # RGB 컬러 이미지
    color_mode='rgb',

    # 테스트 데이터는 순서를 유지한다.
    #
    # 나중에 model.predict() 결과와
    # 실제 이미지 파일 순서를 비교하기 편하기 때문이다.
    shuffle=False,
)


# =============================================================================
# DirectoryIterator에서 실제 NumPy 배열 꺼내기
# =============================================================================

x_train, y_train = train_data[0][0], train_data[0][1]

x_test, y_test = test_data[0][0], test_data[0][1]


# train_data 자체는 numpy 배열이 아니라
# DirectoryIterator 객체이다.
#
# train_data[0]
#
# 은 첫 번째 batch이며 다음 구조를 가진다.
#
# (
#     x,
#     y
# )
#
#
# 따라서:
#
# train_data[0][0]
#
# -> 첫 번째 batch의 x 이미지
#
#
# train_data[0][1]
#
# -> 첫 번째 batch의 y 정답
#
#
# 현재는 batch_size가 전체 데이터 수와 같기 때문에:
#
# train_data[0][0]
#
# 안에 학습 이미지 8005장이 전부 들어있다.


# 사실 아래처럼 더 간단하게 작성해도 된다.
#
# x_train, y_train = train_data[0]
# x_test, y_test = test_data[0]


# =============================================================================
# 데이터 shape 확인
# =============================================================================

print(
    f"x_train shape: {x_train.shape}, "
    f"y_train shape: {y_train.shape}"
)

# 예상:
#
# x_train:
#
# (8005, 100, 100, 3)
#
# 8005 : 이미지 개수
# 100  : 높이
# 100  : 너비
# 3    : RGB 채널
#
#
# y_train:
#
# (8005,)
#
# 이미지 8005장에 대한 정답 8005개


print(
    f"x_test shape: {x_test.shape}, "
    f"y_test shape: {y_test.shape}"
)

# 예상:
#
# x_test:
#
# (2023, 100, 100, 3)
#
# y_test:
#
# (2023,)


# =============================================================================
# 메모리 사용량 참고
# =============================================================================
#
# x_train의 원소 개수:
#
# 8005 × 100 × 100 × 3
#
# = 240,150,000개
#
#
# float32 하나:
#
# 4 byte
#
#
# 따라서:
#
# 240,150,000 × 4
#
# ≈ 960,600,000 byte
#
# ≈ 약 960MB
#
#
# 즉 x_train 하나만으로도 거의 1GB의 RAM을 사용할 수 있다.
#
# 실제로는:
#
# x_test
# CNN 중간 Feature Map
# Gradient
# Weight
# TensorFlow 내부 메모리
#
# 등이 추가되므로 더 많은 메모리가 필요하다.


# =============================================================================
# 2. CNN 모델 구성
# =============================================================================

model = Sequential()

# Sequential:
#
# Layer 1
#   ↓
# Layer 2
#   ↓
# Layer 3
#   ↓
# ...
#
# 처럼 앞 Layer의 출력을
# 다음 Layer의 입력으로 순서대로 연결한다.


# =============================================================================
# 첫 번째 Conv Block
# =============================================================================

model.add(
    Conv2D(
        filters=64,

        # 5 x 5 크기의 filter(kernel)를 사용
        kernel_size=(5, 5),

        # padding='same'
        #
        # 가장자리에 padding을 추가하여
        # 가로/세로 크기를 유지한다.
        #
        # 입력:
        #
        # (100, 100, 3)
        #
        # 출력:
        #
        # (100, 100, 64)
        padding='same',

        # ReLU 활성화 함수
        #
        # x <= 0 -> 0
        # x > 0  -> x
        activation='relu',

        # 첫 Layer이므로 입력 데이터 shape을 지정한다.
        #
        # 이미지 한 장:
        #
        # 높이 100
        # 너비 100
        # RGB 채널 3
        input_shape=(100, 100, 3)
    )
)


# 왜 출력 채널이 64인가?
#
# filters=64
#
# 서로 다른 Filter가 64개 존재하기 때문이다.
#
# Filter 하나
#      ↓
# Feature Map 하나 생성
#
# Filter 64개
#      ↓
# Feature Map 64개 생성
#
# 따라서:
#
# (100,100,3)
#
#      ↓ Conv2D(filters=64)
#
# (100,100,64)


# -----------------------------------------------------------------------------
# 두 번째 Conv2D
# -----------------------------------------------------------------------------

model.add(
    Conv2D(
        filters=64,
        kernel_size=(5, 5),

        # padding을 설정하지 않았기 때문에
        # 기본값:
        #
        # padding='valid'
        #
        # padding을 추가하지 않는다.
        #
        # 출력 크기:
        #
        # (입력 - Kernel) / stride + 1
        #
        # stride 기본값 = 1
        #
        # (100 - 5) / 1 + 1
        #
        # = 96
        #
        # 출력:
        #
        # (96, 96, 64)
        activation='relu'
    )
)


# -----------------------------------------------------------------------------
# MaxPooling
# -----------------------------------------------------------------------------

model.add(
    MaxPooling2D()
)

# 기본 설정:
#
# pool_size=(2,2)
#
# 2 x 2 영역에서 가장 큰 값을 하나 남긴다.
#
#
# 입력:
#
# (96, 96, 64)
#
#       ↓
#
# 출력:
#
# (48, 48, 64)
#
#
# 가로/세로:
#
# 96 -> 48
#
# 절반으로 감소
#
#
# Channel:
#
# 64 -> 64
#
# 그대로 유지된다.


# -----------------------------------------------------------------------------
# Dropout
# -----------------------------------------------------------------------------

model.add(
    Dropout(0.2)
)

# 학습할 때
# Feature Map 출력값 중 약 20%를 랜덤하게 0으로 만든다.
#
# 목적:
#
# 특정 Feature에만 지나치게 의존하는 것을 줄여
# 과적합을 완화한다.
#
#
# Dropout은 shape을 변경하지 않는다.
#
# (48,48,64)
#
#      ↓
#
# (48,48,64)
#
#
# model.evaluate()
# model.predict()
#
# 같은 추론 시점에는 Dropout이 적용되지 않는다.


# =============================================================================
# 두 번째 Conv Block
# =============================================================================

model.add(
    Conv2D(
        filters=32,
        kernel_size=(5, 5),

        # same padding
        #
        # 가로/세로 유지
        #
        # 입력:
        #
        # (48,48,64)
        #
        # 출력:
        #
        # (48,48,32)
        padding='same',

        activation='relu'
    )
)


# -----------------------------------------------------------------------------

model.add(
    Conv2D(
        filters=32,
        kernel_size=(5, 5),

        # padding 기본값='valid'
        #
        # 48 - 5 + 1
        #
        # = 44
        #
        # 출력:
        #
        # (44,44,32)
        activation='relu'
    )
)


# -----------------------------------------------------------------------------

model.add(
    MaxPooling2D()
)

# 기본:
#
# pool_size=(2,2)
#
# 입력:
#
# (44,44,32)
#
#      ↓
#
# 출력:
#
# (22,22,32)


# -----------------------------------------------------------------------------

model.add(
    Dropout(0.25)
)

# 학습 시 약 25%의 출력값을 랜덤하게 0으로 만든다.
#
# shape:
#
# (22,22,32)
#
#      ↓
#
# (22,22,32)


# =============================================================================
# Flatten
# =============================================================================

model.add(
    Flatten()
)

# 현재 Feature Map:
#
# (22, 22, 32)
#
#
# Flatten을 하면:
#
# 22 × 22 × 32
#
# = 15,488
#
#
# 따라서:
#
# (22,22,32)
#
#      ↓ Flatten
#
# (15488,)
#
#
# Flatten은 학습하는 Layer가 아니다.
#
# Weight / Bias 없음
#
# 단순히 배열 모양만 변경한다.


# =============================================================================
# Dense Layer
# =============================================================================

model.add(
    Dense(
        10,
        activation='relu'
    )
)

# 입력:
#
# 15,488개
#
# Dense 뉴런:
#
# 10개
#
#
# 모든 입력이 모든 Dense 뉴런과 연결된다.
#
#
# Parameter 개수:
#
# Weight:
#
# 15,488 × 10
#
# = 154,880
#
#
# Bias:
#
# 10
#
#
# 총:
#
# 154,890개


# -----------------------------------------------------------------------------

model.add(
    Dropout(0.2)
)

# Dense 출력 10개 중
# 학습할 때 약 20%를 랜덤하게 비활성화한다.


# =============================================================================
# 최종 출력 Layer
# =============================================================================

model.add(
    Dense(
        1,
        activation='sigmoid'
    )
)

# 이진분류이므로 출력 뉴런 1개
#
#
# sigmoid:
#
# 출력값을 0 ~ 1 사이로 만든다.
#
#
# 예:
#
# 0.03
# 0.28
# 0.72
# 0.99
#
#
# 만약 class가:
#
# cats = 0
# dogs = 1
#
# 이라면:
#
# 0에 가까움
# -> cats 쪽
#
# 1에 가까움
# -> dogs 쪽
#
#
# 실제 class 번호는:
#
# print(train_data.class_indices)
#
# 로 확인해야 한다.


# =============================================================================
# CNN을 지나면서 Shape 변화 정리
# =============================================================================
#
# 입력
#
# (100,100,3)
#
#       ↓
#
# Conv2D(64, 5x5, same)
#
# (100,100,64)
#
#       ↓
#
# Conv2D(64, 5x5, valid)
#
# (96,96,64)
#
#       ↓
#
# MaxPooling2D
#
# (48,48,64)
#
#       ↓
#
# Dropout
#
# (48,48,64)
#
#       ↓
#
# Conv2D(32, 5x5, same)
#
# (48,48,32)
#
#       ↓
#
# Conv2D(32, 5x5, valid)
#
# (44,44,32)
#
#       ↓
#
# MaxPooling2D
#
# (22,22,32)
#
#       ↓
#
# Dropout
#
# (22,22,32)
#
#       ↓
#
# Flatten
#
# (15488,)
#
#       ↓
#
# Dense(10)
#
# (10,)
#
#       ↓
#
# Dense(1, sigmoid)
#
# (1,)


# =============================================================================
# 3. 모델 Compile
# =============================================================================

model.compile(

    # binary_crossentropy:
    #
    # 정답이 0 또는 1인 이진분류 문제에서
    # 대표적으로 사용하는 Loss 함수
    loss='binary_crossentropy',

    # Adam optimizer
    #
    # 역전파로 계산된 Gradient를 이용하여
    # Weight와 Bias를 수정한다.
    optimizer='adam',

    # 학습하면서 accuracy도 출력
    metrics=['acc']
)


# =============================================================================
# EarlyStopping
# =============================================================================

es = EarlyStopping(

    # validation accuracy를 감시한다.
    monitor='val_acc',

    # Accuracy는 높을수록 좋은 값이므로
    # 최대값을 찾는다.
    mode='max',

    # val_acc가 좋아지지 않아도
    # 최대 130 epoch까지 기다린다.
    patience=130,

    # 학습 종료 후
    # 마지막 epoch의 Weight 대신
    #
    # 가장 val_acc가 좋았던 시점의 Weight를 복원한다.
    restore_best_weights=True,

    # 관련 메시지 출력
    verbose=1
)


# =============================================================================
# 중요!
# =============================================================================
#
# 현재:
#
# epochs=100
# patience=130
#
# 이다.
#
# 즉 최대 학습 자체가 100 epoch인데
# EarlyStopping은 130 epoch 동안 개선되지 않아야 멈춘다.
#
# 따라서 현재 설정에서는 사실상 EarlyStopping이
# 학습을 조기에 종료시킬 수 없다.
#
# 예:
#
# Epoch 1부터 성능이 전혀 좋아지지 않아도
#
# 130 epoch를 기다려야 하는데
#
# 전체 학습은 100 epoch에서 끝나버린다.
#
# 따라서 현재 EarlyStopping은
# "조기 종료" 기능은 사실상 동작하지 않는다.
#
# 다만 restore_best_weights=True 때문에
# 학습 종료 시 best weight 복원과 관련된 동작은
# Keras 버전에 따라 고려될 수 있으므로,
# 일반적으로 patience는 epochs보다 충분히 작게 설정한다.
#
# 예:
#
# patience=10
# patience=20


# =============================================================================
# 모델 저장 파일 이름에 날짜/시간 추가
# =============================================================================

date = datetime.datetime.now().strftime('%m%d_%H%M')


# datetime.datetime.now()
#
# 현재 날짜와 시간을 가져온다.
#
# 예:
#
# 2026-09-21 10:35:42
#
#
# .strftime()
#
# 날짜/시간을 원하는 문자열 형식으로 변환한다.
#
#
# %m = 월
# %d = 일
# %H = 시(24시간)
# %M = 분
#
#
# 따라서:
#
# 2026-09-21 10:35
#
#     ↓
#
# '0921_1035'


# =============================================================================
# 저장될 파일 경로 만들기
# =============================================================================

filepath = (
    f'./_save/keras44/k_{date}_'
    + '{epoch:04d}_{val_acc:.4f}.keras'
)


# 예를 들어:
#
# date:
#
# 0921_1035
#
#
# epoch:
#
# 7
#
#
# val_acc:
#
# 0.923456
#
#
# 라면 저장되는 파일:
#
# ./_save/keras44/
# k_0921_1035_0007_0.9235.keras
#
#
# {epoch:04d}
#
# 4자리 정수로 출력
#
# 1   -> 0001
# 7   -> 0007
# 23  -> 0023
# 100 -> 0100
#
#
# {val_acc:.4f}
#
# 소수점 아래 4자리까지 출력
#
# 0.923456
#
# ->
#
# 0.9235


# =============================================================================
# ModelCheckpoint
# =============================================================================

mcp = ModelCheckpoint(

    # validation accuracy 감시
    monitor='val_acc',

    # 높은 값이 좋은 값
    mode='max',

    # 기존 최고 성능을 갱신했을 때만 저장한다.
    save_best_only=True,

    # 저장 위치 및 파일명
    filepath=filepath,

    # 저장 관련 메시지 출력
    verbose=1
)


# 예:
#
# Epoch 1
#
# val_acc = 0.75
#
# 최초 최고기록
#
# -> 저장
#
#
# Epoch 2
#
# val_acc = 0.80
#
# 0.75보다 좋아짐
#
# -> 저장
#
#
# Epoch 3
#
# val_acc = 0.79
#
# 0.80보다 낮음
#
# -> 저장 X
#
#
# Epoch 4
#
# val_acc = 0.83
#
# 새로운 최고기록
#
# -> 저장
#
#
# 즉 save_best_only=True는:
#
# "매 epoch마다 저장"
#
# 이 아니라
#
# "새로운 최고 기록이 나왔을 때만 저장"
#
# 을 의미한다.


# =============================================================================
# 순수 학습 시간 측정 시작
# =============================================================================

train_start_time = time.time()

# 현재 코드에서는 이 값을 저장하지만
# 아래 최종 출력에서 train_start_time은 사용하지 않는다.
#
# 만약 순수 model.fit() 시간만 보고 싶다면:
#
# train_end_time - train_start_time
#
# 을 계산하면 된다.


# =============================================================================
# 모델 학습
# =============================================================================

model.fit(

    # 학습 입력 데이터
    x_train,

    # 학습 정답 데이터
    y_train,

    # 전체 Dataset을 최대 100번 반복
    epochs=100,

    # 한 번 Gradient를 계산해서
    # Weight를 업데이트할 때 사용할 이미지 수
    batch_size=32,

    # 학습 데이터 중 10%를 Validation 데이터로 사용
    validation_split=0.1,

    # EarlyStopping과 ModelCheckpoint 적용
    callbacks=[es, mcp],

    # 학습 상황 출력
    verbose=1
)


# =============================================================================
# validation_split=0.1 의미
# =============================================================================
#
# 전체:
#
# 8005장
#
#
# 약 90%:
#
# 실제 학습용
#
# 약 7204~7205장
#
#
# 약 10%:
#
# validation용
#
# 약 800장
#
#
# Train 데이터:
#
# Forward
# ↓
# Loss 계산
# ↓
# Backpropagation
# ↓
# Gradient
# ↓
# Weight 수정
#
#
# Validation 데이터:
#
# Forward
# ↓
# val_loss / val_acc 계산
# ↓
# Weight 수정 X
#
#
# 즉 Validation 데이터는
#
# "현재 모델이 학습하지 않은 데이터에서도 잘 맞는가?"
#
# 를 중간중간 확인하기 위해 사용한다.


# =============================================================================
# 두 batch_size를 구분해야 한다.
# =============================================================================
#
# 1.
#
# flow_from_directory(
#     batch_size=8005
# )
#
# 의미:
#
# "디스크에서 이미지 파일을 몇 장씩 꺼내올 것인가?"
#
#
# 2.
#
# model.fit(
#     batch_size=32
# )
#
# 의미:
#
# "Weight를 한 번 업데이트할 때
#  몇 장의 데이터를 사용할 것인가?"
#
#
# 완전히 다른 역할이다.
#
#
# 현재 코드의 실제 흐름:
#
# JPG 8005장
#
#       ↓
#
# flow_from_directory
# batch_size=8005
#
#       ↓
#
# x_train
# (8005,100,100,3)
#
#       ↓
#
# model.fit()
#
#       ↓
#
# 32장 사용
#
#       ↓
#
# Forward
#
#       ↓
#
# Loss
#
#       ↓
#
# Backpropagation
#
#       ↓
#
# Weight 1번 수정
#
#       ↓
#
# 다음 32장
#
#       ↓
#
# 다시 Weight 수정
#
#       ↓
#
# ...


# =============================================================================
# 학습 종료 시간
# =============================================================================

train_end_time = time.time()


