# =============================================================================
# 메모리 관련 참고
# =============================================================================
#
# x_train은:
#
# 8005 × 100 × 100 × 3
#
# = 240,150,000개의 숫자를 가진다.
#
#
# float32라면 숫자 하나가 4 byte이므로:
#
# 약 960MB
#
# 정도의 메모리를 사용할 수 있다.
#
#
# x_test까지 포함하면 이미지 배열만으로
# 약 1.2GB 정도가 될 수 있다.
#
#
# 따라서 현재 코드는
# "NPY로 저장했으니까 RAM도 적게 사용한다"
#
# 는 의미는 아니다.
#
# 핵심 장점은:
#
# "이미지 전처리를 반복하지 않아도 된다."
#
# 는 것이다.



# =============================================================================
# 메모리 확보 관련 참고
# =============================================================================
#
# 필요 없어진 큰 배열은:
#
# del 변수명
#
# 으로 참조를 제거할 수 있다.
#
#
# 예:
#
# del x_test
#
#
# 하지만 현재 x_train, y_train, x_test, y_test는
# 아래 학습과 평가에서 모두 사용해야 한다.
#
# 따라서 지금 여기에서 삭제하면 안 된다.
#
#
# 학습과 평가가 모두 끝난 뒤
# 더 이상 필요하지 않을 때 사용할 수 있다.



# =============================================================================
# 2. CNN 모델 구성
# =============================================================================

model = Sequential()



# =============================================================================
# 첫 번째 Conv2D
# =============================================================================

model.add(
    Conv2D(
        filters=64,

        # 5 x 5 크기의 Kernel(Filter)을 사용한다.
        kernel_size=(5, 5),

        # padding='same'
        #
        # 이미지 가장자리에 Padding을 추가하여
        # 출력의 가로/세로 크기를 입력과 동일하게 유지한다.
        #
        # 입력:
        #
        # (100,100,3)
        #
        # 출력:
        #
        # (100,100,64)
        padding='same',

        # ReLU 활성화 함수
        #
        # x <= 0 → 0
        # x > 0  → x
        activation='relu',

        # 첫 번째 Layer이므로
        # 이미지 한 장의 입력 Shape을 명시한다.
        #
        # 100 : 높이
        # 100 : 너비
        # 3   : RGB 채널
        input_shape=(100, 100, 3)
    )
)


# 왜 출력이:
#
# (100,100,64)
#
# 인가?
#
# filters=64이기 때문이다.
#
#
# Filter 1개
#     ↓
# Feature Map 1개
#
#
# Filter 64개
#     ↓
# Feature Map 64개
#
#
# 따라서 출력 채널이 64개가 된다.



# =============================================================================
# 두 번째 Conv2D
# =============================================================================

model.add(
    Conv2D(
        filters=64,
        kernel_size=(5, 5),

        # padding을 지정하지 않았으므로
        # 기본값:
        #
        # padding='valid'
        #
        # 즉 Padding을 넣지 않는다.
        #
        #
        # 출력 크기 공식:
        #
        # (입력 - Kernel) / stride + 1
        #
        # stride 기본값 = 1
        #
        #
        # (100 - 5) / 1 + 1
        #
        # = 96
        #
        #
        # 따라서:
        #
        # 입력:
        # (100,100,64)
        #
        # 출력:
        # (96,96,64)
        activation='relu'
    )
)



# =============================================================================
# 첫 번째 MaxPooling
# =============================================================================

model.add(
    MaxPooling2D()
)

# 옵션을 생략하면 기본:
#
# pool_size=(2,2)
#
# 이다.
#
# stride 역시 기본적으로 2가 된다.
#
#
# 2 x 2 영역에서
# 가장 큰 값을 하나 남긴다.
#
#
# 입력:
#
# (96,96,64)
#
#      ↓
#
# 출력:
#
# (48,48,64)
#
#
# 가로:
#
# 96 → 48
#
#
# 세로:
#
# 96 → 48
#
#
# 채널:
#
# 64 → 64
#
#
# 즉 공간 크기만 줄고
# Feature Map 개수는 그대로이다.



# =============================================================================
# 첫 번째 Dropout
# =============================================================================

model.add(
    Dropout(0.2)
)

# 학습할 때 출력값 중 약 20%를
# 랜덤하게 0으로 만든다.
#
#
# 목적:
#
# 특정 Feature에만 모델이 지나치게 의존하는 것을 줄여
# 과적합을 완화한다.
#
#
# Shape은 변하지 않는다.
#
# (48,48,64)
#      ↓
# (48,48,64)
#
#
# Dropout은 학습할 때만 동작한다.
#
# model.evaluate()
# model.predict()
#
# 와 같은 평가/추론 과정에서는
# Dropout이 적용되지 않는다.



# =============================================================================
# 세 번째 Conv2D
# =============================================================================

model.add(
    Conv2D(
        filters=32,
        kernel_size=(5, 5),

        # same padding이므로
        # 공간 크기는 유지된다.
        #
        # 입력:
        #
        # (48,48,64)
        #
        # 출력:
        #
        # (48,48,32)
        padding='same',

        activation='relu'
    )
)


# filters가:
#
# 64 → 32
#
# 로 바뀌었으므로
#
# 출력 Feature Map 개수도:
#
# 32개
#
# 가 된다.



# =============================================================================
# 네 번째 Conv2D
# =============================================================================

model.add(
    Conv2D(
        filters=32,
        kernel_size=(5, 5),

        # padding 기본값 = valid
        #
        # 출력 크기:
        #
        # 48 - 5 + 1
        #
        # = 44
        #
        #
        # 입력:
        #
        # (48,48,32)
        #
        # 출력:
        #
        # (44,44,32)
        activation='relu'
    )
)



# =============================================================================
# 두 번째 MaxPooling
# =============================================================================

model.add(
    MaxPooling2D()
)

# 입력:
#
# (44,44,32)
#
#       ↓
#
# 2 x 2 MaxPooling
#
#       ↓
#
# 출력:
#
# (22,22,32)



# =============================================================================
# 두 번째 Dropout
# =============================================================================

model.add(
    Dropout(0.25)
)

# 학습할 때 약 25%의 출력을
# 랜덤하게 비활성화한다.
#
#
# Shape:
#
# (22,22,32)
#
#      ↓
#
# (22,22,32)



# =============================================================================
# Flatten
# =============================================================================

model.add(
    Flatten()
)

# 현재 Feature Map:
#
# (22,22,32)
#
#
# Flatten을 사용하면:
#
# 22 × 22 × 32
#
# = 15,488
#
#
# 따라서:
#
# (22,22,32)
#
#       ↓ Flatten
#
# (15488,)
#
#
# 즉 다차원 Feature Map을
# Dense Layer에 넣기 위해
# 1차원으로 쭉 펼친다.
#
#
# Flatten 자체에는
# 학습되는 Weight와 Bias가 없다.



# =============================================================================
# Dense Layer
# =============================================================================

model.add(
    Dense(
        10,
        activation='relu'
    )
)

# 입력:
#
# 15,488개
#
#       ↓
#
# Dense 뉴런:
#
# 10개
#
#
# 모든 입력이 모든 뉴런과 연결된다.
#
#
# Weight 개수:
#
# 15,488 × 10
#
# = 154,880
#
#
# Bias:
#
# 10
#
#
# 총 Parameter:
#
# 154,890개



# =============================================================================
# Dense 뒤 Dropout
# =============================================================================

model.add(
    Dropout(0.2)
)

# Dense Layer의 출력에
# Dropout 20% 적용
#
# 과적합 완화 목적



# =============================================================================
# 최종 출력 Layer
# =============================================================================

model.add(
    Dense(
        1,
        activation='sigmoid'
    )
)

# 개 / 고양이
#
# 두 개의 class를 구분하는
# Binary Classification이므로
# 최종 출력 뉴런은 1개이다.
#
#
# sigmoid:
#
# 출력값을 0 ~ 1 사이로 만든다.
#
#
# 예:
#
# 0.02
# 0.35
# 0.73
# 0.98
#
#
# 만약:
#
# cats = 0
# dogs = 1
#
# 이라면
#
# 0에 가까울수록 cat 쪽
#
# 1에 가까울수록 dog 쪽
#
# 으로 해석할 수 있다.
#
#
# 정확한 class 번호는
# NPY를 만들기 전:
#
# train_data.class_indices
#
# 를 확인해야 한다.



# =============================================================================
# CNN을 통과하면서 Shape이 어떻게 변하는지 정리
# =============================================================================
#
# 입력 이미지
#
# (100,100,3)
#
#       ↓
#
# Conv2D(64, 5x5, same)
#
# (100,100,64)
#
#       ↓
#
# Conv2D(64, 5x5, valid)
#
# (96,96,64)
#
#       ↓
#
# MaxPooling2D
#
# (48,48,64)
#
#       ↓
#
# Dropout
#
# (48,48,64)
#
#       ↓
#
# Conv2D(32, 5x5, same)
#
# (48,48,32)
#
#       ↓
#
# Conv2D(32, 5x5, valid)
#
# (44,44,32)
#
#       ↓
#
# MaxPooling2D
#
# (22,22,32)
#
#       ↓
#
# Dropout
#
# (22,22,32)
#
#       ↓
#
# Flatten
#
# (15488,)
#
#       ↓
#
# Dense(10)
#
# (10,)
#
#       ↓
#
# Dropout
#
# (10,)
#
#       ↓
#
# Dense(1, sigmoid)
#
# (1,)



# =============================================================================
# 3. 모델 Compile
# =============================================================================

model.compile(

    # Binary Cross Entropy
    #
    # 정답이:
    #
    # 0 또는 1
    #
    # 인 이진분류 문제에서
    # 대표적으로 사용하는 Loss 함수
    loss='binary_crossentropy',

    # Adam Optimizer
    #
    # Backpropagation으로 계산된 Gradient를 바탕으로
    # Weight와 Bias를 업데이트한다.
    optimizer='adam',

    # 학습 과정에서 Accuracy도 같이 계산
    metrics=['acc']
)



# =============================================================================
# EarlyStopping 설정
# =============================================================================

early_stopping = EarlyStopping(

    # 학습 Accuracy가 아니라
    # Validation Accuracy를 감시한다.
    monitor='val_acc',

    # Accuracy는 높을수록 좋으므로
    # 최대값 방향으로 감시
    mode='max',

    # val_acc가 좋아지지 않아도
    # 130 epoch까지 기다린다.
    patience=130,

    # 학습이 끝나면
    # 마지막 epoch의 Weight가 아니라
    #
    # val_acc가 가장 좋았던 epoch의 Weight로
    # 모델을 되돌린다.
    restore_best_weights=True,

    # 메시지 출력
    verbose=1
)



# =============================================================================
# 중요한 점: 현재 epochs와 patience 설정
# =============================================================================
#
# 아래 model.fit()은:
#
# epochs=100
#
# 인데
#
# EarlyStopping은:
#
# patience=130
#
# 이다.
#
#
# 즉:
#
# "130 epoch 동안 val_acc가 개선되지 않으면 중단"
#
# 해야 하는데
#
# 모델 자체가 최대 100 epoch까지만 학습한다.
#
#
# 따라서 현재 설정에서는 EarlyStopping이
# 조기에 학습을 중단시키는 역할을 사실상 수행할 수 없다.
#
#
# EarlyStopping을 실제로 사용하고 싶다면 예:
#
# patience=10
#
# 또는
#
# patience=20
#
# 처럼 epochs보다 작은 값을 사용하는 것이 일반적이다.



# =============================================================================
# ModelCheckpoint 파일 이름 만들기
# =============================================================================

date = datetime.datetime.now().strftime('%m%d_%H%M')

# 현재 날짜와 시간을 가져온다.
#
# 예:
#
# 2026-09-21 11:30
#
#
# strftime('%m%d_%H%M')
#
# 결과:
#
# 0921_1130
#
#
# %m = 월
# %d = 일
# %H = 시
# %M = 분



# =============================================================================
# ModelCheckpoint 저장 경로
# =============================================================================

filepath = (
    f'./_save/keras45/k_{date}_'
    + '{epoch:04d}_{val_acc:.4f}.keras'
)


# 예를 들어:
#
# date:
#
# 0921_1130
#
#
# epoch:
#
# 7
#
#
# val_acc:
#
# 0.923456
#
#
# 이라면 저장될 파일:
#
# ./_save/keras45/
# k_0921_1130_0007_0.9235.keras
#
#
# {epoch:04d}
#
# epoch를 4자리 숫자로 표현
#
# 1   → 0001
# 7   → 0007
# 23  → 0023
# 100 → 0100
#
#
# {val_acc:.4f}
#
# val_acc를 소수점 아래 4자리까지 표현
#
# 0.923456
#
# →
#
# 0.9235
#
#
# 주의:
#
# ./_save/keras45/
