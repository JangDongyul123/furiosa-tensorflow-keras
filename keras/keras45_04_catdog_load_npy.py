#
# 이미 0~1로 변환된 데이터를
# 또 255로 나누게 되기 때문이다.



# =============================================================================
# 학습 데이터 정답 y_train
# =============================================================================

y_train = np.load(
    np_path + 'keras45_03_y_train.npy'
)

# 예상 shape:
#
# (8005,)
#
# 예:
#
# [0., 1., 0., 1., ...]
#
#
# 이전에:
#
# class_mode='binary'
#
