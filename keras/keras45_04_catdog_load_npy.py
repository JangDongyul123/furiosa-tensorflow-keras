import numpy as np
import time
import datetime

# Sequential
# - Layer를 위에서 아래 방향으로 순서대로 쌓는 모델
#
# 입력
#  ↓
# Layer 1
#  ↓
# Layer 2
#  ↓
# Layer 3
#  ↓
# 출력
from tensorflow.keras.models import Sequential


# Dense         : 모든 입력과 모든 뉴런이 연결되는 완전연결층
# Conv2D        : 이미지에서 특징을 추출하는 2차원 합성곱층
# Flatten       : 3차원 Feature Map을 1차원으로 펼침
# Dropout       : 학습 중 일부 출력을 랜덤하게 0으로 만들어 과적합 완화
# MaxPooling2D  : Feature Map의 가로/세로 크기를 줄여 특징을 요약
from tensorflow.keras.layers import (
    Dense,
    Conv2D,
    Flatten,
    Dropout,
    MaxPooling2D
)


# EarlyStopping
# - 검증 성능이 일정 기간 좋아지지 않으면 학습을 중단
#
# ModelCheckpoint
# - 학습 중 성능이 가장 좋은 모델을 파일로 저장
from tensorflow.keras.callbacks import (
    EarlyStopping,
    ModelCheckpoint
)


# 실제 정답과 모델의 예측값을 비교하여
# Accuracy를 계산하는 sklearn 함수
from sklearn.metrics import accuracy_score



