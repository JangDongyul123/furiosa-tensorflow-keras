# → 모델 저장
#
#
# Epoch 4
# val_acc = 0.82
#
# → 저장 X
#
#
# Epoch 5
# val_acc = 0.86
#
# → 새로운 최고 기록
# → 모델 저장



# =============================================================================
# EarlyStopping과 ModelCheckpoint의 차이
# =============================================================================
#
# EarlyStopping
#
# "언제 학습을 멈출 것인가?"
#
#
# ModelCheckpoint
#
# "어떤 시점의 모델을 파일로 저장할 것인가?"
#
#
# 서로 역할이 다르기 때문에
# 동시에 사용할 수 있다.



# =============================================================================
# 학습 시간 측정 시작
# =============================================================================

start_time_train = time.time()



# =============================================================================
# 모델 학습
# =============================================================================

model.fit(

    # 학습 이미지
    x_train,

    # 학습 이미지의 정답
    y_train,

    # 전체 데이터를 최대 100번 반복
    epochs=100,

    # 한 번 Gradient를 계산해서
    # Weight를 업데이트할 때 사용할 이미지 개수
    batch_size=32,

    # x_train 중 10%를 Validation 데이터로 사용
    validation_split=0.1,

    # EarlyStopping
    # +
    # ModelCheckpoint
    #
    # 두 Callback을 동시에 사용
    callbacks=[
        early_stopping,
        mcp
    ],

    # 학습 진행 상황 출력
    verbose=1
)



# =============================================================================
# validation_split=0.1
# =============================================================================
#
# 전체:
#
# 8005장
#
#
# 약 90%:
#
# 실제 학습
#
# 약 7204~7205장
#
#
# 약 10%:
#
# Validation
#
# 약 800장
#
#
# Training 데이터:
#
# Forward
# ↓
# Loss 계산
# ↓
# Backpropagation
# ↓
# Gradient 계산
# ↓
# Weight 업데이트
#
#
# Validation 데이터:
#
# Forward
# ↓
# val_loss 계산
# ↓
# val_acc 계산
#
# Weight 업데이트 X



# =============================================================================
# batch_size=32
# =============================================================================
#
# 약 7205장의 실제 학습 데이터를
#
# 한꺼번에 Gradient 계산하는 것이 아니라
# 32장씩 나눠서 사용한다.
#
#
# 32장
#
# ↓
#
# Forward
#
# ↓
#
# Loss 계산
#
# ↓
#
# Backpropagation
#
# ↓
#
# Weight 업데이트 1회
#
#
# 다음 32장
#
# ↓
#
# Weight 업데이트 2회
#
#
# ...
#
#
# 약:
#
# 7205 / 32
#
# ≈ 225 batch
#
#
# 즉 한 Epoch마다
# 대략 225번 정도 Weight가 업데이트된다.
#
# 마지막 batch는 32장보다 적을 수 있다.



