# import os
# os.makedirs('./_save/keras45/', exist_ok=True)
#
# 를 사용할 수 있다.



# =============================================================================
# ModelCheckpoint 생성
# =============================================================================

mcp = ModelCheckpoint(

    # val_acc를 감시한다.
    monitor='val_acc',

    # accuracy는 높은 것이 좋은 값
    mode='max',

    # 모든 epoch를 저장하는 것이 아니라
    #
    # "기존 최고 val_acc보다 좋아졌을 때만"
    #
    # 저장한다.
    save_best_only=True,

    # 저장 경로
    filepath=filepath,

    # 저장 메시지 출력
    verbose=1
)


# 예:
#
# Epoch 1
# val_acc = 0.80
#
# → 현재 최고
# → 모델 저장
#
#
# Epoch 2
# val_acc = 0.78
#
# → 0.80보다 낮음
# → 저장 X
#
#
# Epoch 3
# val_acc = 0.83
#
