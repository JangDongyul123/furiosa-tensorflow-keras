import numpy as np
import time

# 이미지 파일을 읽으면서 전처리할 수 있는 클래스
# 여기서는 픽셀값을 0~1로 스케일링하는 용도로 사용
from tensorflow.keras.preprocessing.image import ImageDataGenerator

# Sequential : 레이어를 순서대로 쌓는 모델
from tensorflow.keras.models import Sequential

# Dense         : 완전연결층
# Conv2D        : 이미지의 특징을 추출하는 합성곱층
# Flatten       : 다차원 Feature Map을 1차원으로 펼침
# Dropout       : 일부 뉴런을 랜덤하게 끄면서 과적합 방지
# MaxPooling2D  : Feature Map의 가로/세로 크기를 줄임
from tensorflow.keras.layers import (
    Dense,
    Conv2D,
    Flatten,
    Dropout,
    MaxPooling2D
)

# 검증 성능이 더 이상 좋아지지 않으면 학습을 조기에 종료
from tensorflow.keras.callbacks import EarlyStopping

# 실제 정답과 예측값을 이용하여 정확도 계산
from sklearn.metrics import accuracy_score


# =============================================================================
# 1. 데이터 준비
# =============================================================================


# -----------------------------------------------------------------------------
# ImageDataGenerator
# -----------------------------------------------------------------------------
# 이미지 픽셀값은 일반적으로 0 ~ 255 범위를 가진다.
#
# rescale=1./255를 적용하면
#
# 0   -> 0.0
# 128 -> 약 0.502
# 255 -> 1.0
#
# 즉, 모든 픽셀값을 0 ~ 1 범위로 스케일링한다.
#
# 이전 코드와 달리
# horizontal_flip, rotation_range 등의 데이터 증강은 사용하지 않는다.
#
# 따라서 여기서는 단순히 "이미지 스케일링"만 수행한다.

train_datagen = ImageDataGenerator(
    rescale=1./255
)

test_datagen = ImageDataGenerator(
    rescale=1./255
)


# -----------------------------------------------------------------------------
# 이미지 폴더 경로
# -----------------------------------------------------------------------------

path_train = './_data/image/brain/train/'
path_test = './_data/image/brain/test/'


# 폴더 구조는 대략 다음과 같다고 보면 된다.
#
# brain/
#
# ├── train/
# │   ├── ad/
# │   │   ├── image1.jpg
# │   │   └── ...
# │   │
# │   └── normal/
# │       ├── image1.jpg
# │       └── ...
# │
# └── test/
#     ├── ad/
#     └── normal/
#
#
# flow_from_directory()는 하위 폴더 이름을 이용하여
# 자동으로 정답 라벨을 만든다.
#
# 예:
#
# ad     -> 0
# normal -> 1
#
# 단, 실제 class 번호는 알파벳 순서 등에 의해 결정되므로
#
# print(train_data.class_indices)
#
# 를 통해 직접 확인하는 것이 가장 정확하다.


# =============================================================================
# 학습 데이터 가져오기
# =============================================================================

train_data = train_datagen.flow_from_directory(

    # 이미지가 들어있는 최상위 폴더
    path_train,

    # 원본 이미지 크기가 제각각이어도
    # 모두 150 x 150 크기로 변환해서 가져온다.
    #
    # 채널 수는 여기에서 적지 않는다.
    target_size=(150, 150),

    # 학습 이미지 전체가 160장이므로
    # batch_size=160으로 설정하면 한 번에 160장을 가져온다.
    #
    # 즉:
    #
    # 전체 데이터 = 160장
    # batch_size = 160
    #
    # → batch가 사실상 1개
    #
    # train_data[0] 안에 전체 데이터가 들어가게 된다.
    batch_size=160,

    # 클래스가 2개이므로 binary 사용
    #
    # y가 다음과 같은 형태로 만들어진다.
    #
    # [0., 1., 1., 0., 1., ...]
    class_mode='binary',

    # 이미지를 흑백으로 읽는다.
    #
    # 따라서 이미지 한 장의 shape은
    #
    # (150, 150, 1)
    #
    # 마지막 1은 grayscale 채널을 의미한다.
    color_mode='grayscale',

    # 학습 데이터의 순서를 랜덤하게 섞는다.
    shuffle=True,
)


# 실행 시 예:
#
# Found 160 images belonging to 2 classes.


# =============================================================================
# 테스트 데이터 가져오기
# =============================================================================

test_data = test_datagen.flow_from_directory(

    path_test,

    # train과 동일한 이미지 크기로 통일
    target_size=(150, 150),

    # 테스트 이미지가 총 120장이므로
    # 120장을 한 번에 가져온다.
    batch_size=120,

    # 이진 분류
    class_mode='binary',

    # 흑백 이미지
    color_mode='grayscale',

    # 테스트 데이터는 순서를 유지하는 것이 좋다.
    #
    # 나중에 predict 결과와 원본 데이터의 순서를
    # 비교하기 편하기 때문이다.
    shuffle=False,
)


# 실행 시 예:
#
# Found 120 images belonging to 2 classes.


# =============================================================================
# DirectoryIterator에서 실제 x, y 배열 꺼내기
# =============================================================================

# train_data 자체는 numpy 배열이 아니라
# DirectoryIterator 객체이다.
#
# 구조:
#
# train_data[0]
#      │
#      ├── [0] : x 데이터
#      └── [1] : y 데이터
#
#
# batch_size=160이고 전체 이미지가 160장이므로
# train_data[0]에 전체 학습 데이터가 들어있다.

x_train = train_data[0][0]
y_train = train_data[0][1]

x_test = test_data[0][0]
y_test = test_data[0][1]


# 위 코드를 tuple unpacking으로 한 줄로 적으면:
#
# x_train, y_train = train_data[0]
# x_test, y_test = test_data[0]
#
# 와 같은 의미이다.


print(x_train.shape, y_train.shape)

# 출력:
#
# (160, 150, 150, 1) (160,)
#
# x_train
#
# 160 : 이미지 개수
# 150 : 높이
# 150 : 너비
# 1   : grayscale 채널
#
#
# y_train
#
# (160,)
#
# 이미지 160장에 대응하는 정답 160개


print(x_test.shape, y_test.shape)

# 출력:
#
# (120, 150, 150, 1) (120,)
#
# 테스트 이미지 120장
# 각각 150 x 150 크기의 흑백 이미지


# =============================================================================
# 2. CNN 모델 구성
# =============================================================================

model = Sequential()


# -----------------------------------------------------------------------------
# Conv2D 1
# -----------------------------------------------------------------------------

model.add(
    Conv2D(
        filters=64,

        # 3 x 3 크기의 필터 사용
        kernel_size=(3, 3),

        # padding='same'
        #
        # 입력 이미지 가장자리에 padding을 추가하여
        # 출력의 가로/세로 크기를 입력과 동일하게 유지한다.
        #
        # 입력:
        # (150, 150, 1)
        #
        # 출력:
        # (150, 150, 64)
        padding='same',

        # 음수는 0으로 만들고 양수는 그대로 통과
        activation='relu',

        # 모델의 첫 번째 레이어이므로
        # 입력 데이터의 shape을 명시한다.
        #
        # 이미지 한 장:
        # 150 x 150 x 1
        input_shape=(150, 150, 1)
    )
)


# 첫 Conv2D를 통과하면
#
# (150, 150, 1)
#
#      ↓ Conv2D filters=64
#
# (150, 150, 64)
#
#
# 필터 64개가 각각 하나의 Feature Map을 만들기 때문에
# 출력 채널이 64개가 된다.


# -----------------------------------------------------------------------------
# Conv2D 2
# -----------------------------------------------------------------------------

model.add(
    Conv2D(
        filters=64,
        kernel_size=(3, 3),

        # padding을 지정하지 않았으므로 기본값은 'valid'
        #
        # 즉, padding 없이 합성곱한다.
        #
        # 출력 크기 공식:
        #
        # (입력크기 - 커널크기) / stride + 1
        #
        # stride 기본값 = 1
        #
        # (150 - 3) / 1 + 1
        # = 148
        #
        # 따라서:
        #
        # (150,150,64)
        #       ↓
        # (148,148,64)
        activation='relu'
    )
)


# -----------------------------------------------------------------------------
# MaxPooling2D
# -----------------------------------------------------------------------------

model.add(
    MaxPooling2D()
)

# 옵션을 생략하면 기본적으로
#
# pool_size=(2, 2)
#
# 를 사용한다.
#
# 2 x 2 영역에서 가장 큰 값 하나만 남긴다.
#
#
# 입력:
#
# (148, 148, 64)
#
#       ↓ 2 x 2 MaxPooling
#
# 출력:
#
# (74, 74, 64)
#
#
# 채널 수는 그대로 64이고
# 가로/세로 크기만 절반 정도로 줄어든다.
#
# 목적:
#
# - 연산량 감소
# - 중요한 특징 요약
# - 작은 위치 변화에 덜 민감하게 만듦


# -----------------------------------------------------------------------------
# Dropout
# -----------------------------------------------------------------------------

model.add(
    Dropout(0.2)
)

# 학습 중 뉴런의 출력 중 약 20%를 랜덤하게 0으로 만든다.
#
# 특정 뉴런들만 지나치게 의존하는 것을 막아
# 과적합을 완화하기 위한 방법이다.
#
# 주의:
#
# Dropout은 학습할 때만 적용되고
# model.predict(), model.evaluate() 같은 추론 과정에서는 꺼진다.
#
# shape은 변하지 않는다.
#
# (74,74,64)
#      ↓
# (74,74,64)


# =============================================================================
# 두 번째 Conv Block
# =============================================================================


# -----------------------------------------------------------------------------
# Conv2D 3
# -----------------------------------------------------------------------------

model.add(
    Conv2D(
        filters=32,
        kernel_size=(3, 3),

        # padding='same'이므로 가로/세로 크기 유지
        #
        # 입력:
        # (74,74,64)
        #
        # 출력:
        # (74,74,32)
        #
        # filters=32이므로 출력 채널은 32
        padding='same',
        activation='relu'
    )
)


# -----------------------------------------------------------------------------
# Conv2D 4
# -----------------------------------------------------------------------------

model.add(
    Conv2D(
        filters=32,
        kernel_size=(3, 3),

        # padding 기본값='valid'
        #
        # 74 - 3 + 1 = 72
        #
        # 입력:
        # (74,74,32)
        #
        # 출력:
        # (72,72,32)
        activation='relu'
    )
)


# -----------------------------------------------------------------------------
# 두 번째 MaxPooling
# -----------------------------------------------------------------------------

model.add(
    MaxPooling2D()
)

# 입력:
#
# (72,72,32)
#
# 2 x 2 pooling
#
#       ↓
#
# 출력:
#
# (36,36,32)


# -----------------------------------------------------------------------------
# Dropout 25%
# -----------------------------------------------------------------------------

model.add(
    Dropout(0.25)
)

# 학습할 때 약 25%의 출력을 랜덤하게 끈다.
#
# shape:
#
# (36,36,32)
#       ↓
# (36,36,32)


# =============================================================================
# CNN의 Feature Map을 Dense에 넣기 위해 1차원으로 펼친다.
# =============================================================================

model.add(
    Flatten()
)

# Flatten 전:
#
# (36, 36, 32)
#
# Flatten 후:
#
# 36 × 36 × 32
# = 41,472
#
# 따라서 출력:
#
# (41472,)
#
#
# Flatten은 값을 학습하는 레이어가 아니다.
#
# 단순히 배열의 모양을 바꾸는 역할만 한다.
#
# 예:
#
# 3차원 Feature Map
#
# (36,36,32)
#
#       ↓ Flatten
#
# 1차원 벡터
#
# (41472,)


# =============================================================================
# Dense 영역
# =============================================================================


model.add(
    Dense(
        10,
        activation='relu'
    )
)

# Flatten 결과 41,472개의 값을
# 10개의 뉴런으로 연결한다.
#
#
# 입력:
#
# (41472,)
#
#       ↓
#
# 출력:
#
# (10,)
#
#
# Dense 파라미터 수:
#
# 41,472 × 10 + bias 10
#
# = 414,730개
#
# 따라서 이 모델에서는 Flatten 이후 Dense에서
# 상당히 많은 파라미터가 발생한다.


model.add(
    Dropout(0.2)
)

# Dense 뉴런의 약 20%를 학습 중 랜덤하게 끈다.
#
# 과적합 완화 목적


# =============================================================================
# 최종 출력층
# =============================================================================

model.add(
    Dense(
        1,

        # sigmoid는 결과를 0 ~ 1 사이의 값으로 만든다.
        #
        # 예:
        #
        # 0.02
        # 0.31
        # 0.78
        # 0.99
        #
        # 이를 클래스 0에 속할지 1에 속할지 판단하는
        # 확률처럼 해석할 수 있다.
        activation='sigmoid'
    )
)

# 이진 분류이므로 최종 뉴런은 1개
#
# 예:
#
# 0.1 -> class 0 쪽
# 0.9 -> class 1 쪽


# =============================================================================
# 모델 전체 구조 출력
# =============================================================================

model.summary()

# 각 레이어별
#
# - 출력 Shape
# - 학습할 Parameter 수
#
# 등을 확인할 수 있다.


# =============================================================================
# 3. 모델 컴파일
# =============================================================================

model.compile(

    # 이진 분류에 대표적으로 사용하는 손실함수
    loss='binary_crossentropy',

    # Adam Optimizer
    #
    # 역전파를 통해 계산된 Gradient를 이용하여
    # 가중치 w와 bias b를 업데이트한다.
    optimizer='adam',

    # 학습 중 정확도도 같이 출력
    metrics=['acc']
)


# =============================================================================
# EarlyStopping 설정
# =============================================================================

early_stopping = EarlyStopping(

    # 검증 데이터의 정확도(val_acc)를 감시한다.
    monitor='val_acc',

    # val_acc는 클수록 좋은 값이므로 사실상 max 방향으로 감시한다.
    #
    # mode='auto'이면 Keras가 monitor 이름을 보고
    # 증가해야 좋은 지표인지 감소해야 좋은 지표인지 판단한다.
    mode='auto',

    # 검증 정확도가 개선되지 않더라도
    # 최대 130 epoch까지 기다린다.
    #
    # patience가 상당히 큰 설정이다.
    patience=130,

    # EarlyStopping이 발생하면
    # 마지막 epoch의 가중치가 아니라
    # 검증 성능이 가장 좋았던 시점의 가중치로 되돌린다.
    restore_best_weights=True,

    # EarlyStopping 관련 메시지 출력
    verbose=1
)


# =============================================================================
# 학습 시간 측정 시작
# =============================================================================

start_time = time.time()


# =============================================================================
# 모델 학습
# =============================================================================

model.fit(

    # 학습할 이미지 데이터
    x_train,

    # 학습 데이터의 정답
    y_train,

    # 전체 학습 데이터를 최대 200번 반복
    epochs=200,

    # 한 번의 Gradient 업데이트에 사용할 데이터 개수
    batch_size=13,

    # x_train 160장 중 30%를 검증용 데이터로 사용한다.
    #
    # 약:
    #
    # train:
    # 160 × 0.7 ≈ 112장
    #
    # validation:
    # 160 × 0.3 ≈ 48장
    #
    # 이 검증 데이터는 가중치 학습에는 사용되지 않고
    # 학습 중 모델의 일반화 성능을 확인하는 데 사용된다.
    validation_split=0.3,

    # 위에서 만든 EarlyStopping 적용
    callbacks=[early_stopping],

    # epoch 진행 상황 출력
    verbose=1
)


# =============================================================================
# 학습 종료 시간 측정
# =============================================================================

end_time = time.time()


# =============================================================================
# 4. 테스트 데이터로 최종 모델 평가
# =============================================================================

loss = model.evaluate(
    x_test,
    y_test,
    verbose=1
)

# model.compile()에서
#
# loss='binary_crossentropy'
# metrics=['acc']
#
# 를 설정했기 때문에
#
# model.evaluate() 결과는 다음 구조이다.
#
# loss[0] = binary_crossentropy loss
# loss[1] = accuracy


print(f"loss : {loss[0]}")
print(f"acc : {loss[1]}")


# =============================================================================
# 5. 테스트 데이터 예측
# =============================================================================

y_pred = model.predict(x_test)

# sigmoid 출력이므로 아직 다음과 같은 실수값이다.
#
# 예:
#
# [[0.923],
#  [0.132],
#  [0.782],
#  [0.048]]
#
#
# shape:
#
# (120, 1)


# =============================================================================
# 6. 확률을 0 또는 1로 변환
# =============================================================================

y_pred = np.round(y_pred)

# np.round()를 적용하면
#
# 0.1 -> 0
# 0.3 -> 0
# 0.7 -> 1
# 0.9 -> 1
#
# 처럼 변환된다.
#
# 즉, 약 0.5를 기준으로
# class 0 / class 1로 나누는 것과 비슷하다.


# =============================================================================
# 7. sklearn으로 정확도 다시 계산
# =============================================================================

print(
    f"accuracy_score : {accuracy_score(y_test, y_pred)}"
)

# y_test:
# 실제 정답
#
# y_pred:
# 모델이 예측한 정답
#
#
# 예:
#
# y_test
# [0, 1, 1, 0]
#
# y_pred
# [0, 1, 0, 0]
#
# 4개 중 3개 정답
#
# accuracy = 3 / 4 = 0.75


# =============================================================================
# 8. 학습 소요 시간 출력
# =============================================================================

print(
    f"소요 시간 : {round(end_time - start_time, 2)} 초"
)


# =============================================================================
# 전체 흐름 정리
# =============================================================================
#
# JPG 이미지 파일
#
#       ↓
#
# ImageDataGenerator
# rescale=1./255
#
#       ↓
#
# flow_from_directory()
#
#       ↓
#
# DirectoryIterator
#
#       ↓
#
# train_data[0]
#
#       ↓
#
# x_train / y_train
#
#       ↓
#
# CNN
#
# Conv2D
#   ↓
# Conv2D
#   ↓
# MaxPooling
#   ↓
# Dropout
#   ↓
# Conv2D
#   ↓
# Conv2D
#   ↓
# MaxPooling
#   ↓
# Dropout
#   ↓
# Flatten
#   ↓
# Dense
#   ↓
