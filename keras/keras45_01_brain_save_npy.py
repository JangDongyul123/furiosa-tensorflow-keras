import numpy as np
import time

# ImageDataGenerator:
# 이미지 파일을 폴더에서 읽어오고,
# 크기 조절, 픽셀 스케일링, 데이터 증강 등을 수행할 수 있는 클래스
from tensorflow.keras.preprocessing.image import ImageDataGenerator


# =============================================================================
# 1. 이미지 데이터를 NumPy 배열로 변환한 뒤 NPY 파일로 저장
# =============================================================================
#
# 목적:
#
# 원래 이미지 데이터는 .jpg, .png 등의 압축된 이미지 파일이다.
#
# 매번 학습할 때마다:
#
# JPG 파일 열기
#      ↓
# 이미지 압축 해제
#      ↓
# 150 x 150 크기로 resize
#      ↓
# grayscale 변환
#      ↓
# 0~255 → 0~1 스케일링
#      ↓
# NumPy 배열 생성
#
# 과정을 다시 수행해야 한다.
#
# 이미지가 많으면 이 전처리 과정 자체가 시간이 걸린다.
#
#
# 그래서 한 번 전처리한 결과를:
#
# x_train.npy
# y_train.npy
# x_test.npy
# y_test.npy
#
# 형태로 저장해두면 다음부터는
#
# np.load()
#
# 한 번으로 바로 NumPy 배열을 가져올 수 있다.
#
#
# 즉:
#
# 최초 1회
#
# JPG
# ↓
# 전처리
# ↓
# NumPy
# ↓
# NPY 저장
#
#
# 이후
#
# NPY
# ↓
# np.load()
# ↓
# 바로 학습
#
# 으로 사용할 수 있다.


# =============================================================================
# 데이터 변환 시간 측정 시작
# =============================================================================

start_time = time.time()

# 현재 시간을 초 단위로 저장한다.
#
# 나중에:
#
# time.time() - start_time
#
# 을 계산하면
# JPG 이미지들을 읽고 NumPy 배열로 변환하는 데
# 얼마나 걸렸는지 알 수 있다.


# =============================================================================
# ImageDataGenerator 생성
# =============================================================================

train_datagen = ImageDataGenerator(
    rescale=1./255
)

test_datagen = ImageDataGenerator(
    rescale=1./255
)

# 이미지의 픽셀값은 일반적으로:
#
# 0 ~ 255
#
# 범위이다.
#
#
# rescale=1./255
#
# 를 적용하면 모든 픽셀값에 1/255를 곱한다.
#
# 예:
#
# 0   -> 0.0
# 128 -> 약 0.502
# 255 -> 1.0
#
#
# 따라서:
#
# 0 ~ 255
#
#     ↓
#
# 0 ~ 1
#
# 로 스케일링된다.
#
#
# 주의:
#
# 현재 코드에서는
#
# horizontal_flip
# rotation_range
# zoom_range
#
# 등을 사용하지 않으므로
# 데이터 증강은 하지 않는다.
#
# 단순히 rescale만 수행한다.
#
#
# NPY 저장용 코드에서는 이런 방식이 이해하기 쉽다.
#
# 만약 랜덤 데이터 증강까지 적용해서 NPY로 저장해버리면
# 그 순간 만들어진 랜덤 변형 이미지가 그대로 고정되어 버리기 때문이다.


# =============================================================================
# 이미지 데이터 폴더 경로
# =============================================================================

path_train = './_data/image/brain/train/'
path_test = './_data/image/brain/test/'


# 예를 들어 폴더 구조가:
#
# brain/
#
# ├── train/
# │   ├── ad/
# │   │   ├── image001.jpg
# │   │   └── ...
# │   │
# │   └── normal/
# │       ├── image001.jpg
# │       └── ...
# │
# └── test/
#     ├── ad/
#     └── normal/
#
# 형태라고 보면 된다.
#
#
# flow_from_directory()는
# train 바로 아래의 하위 폴더를 보고
# 자동으로 class를 만든다.
#
# 예:
#
# ad
# normal
#
# 두 폴더가 있으면
# 클래스가 2개라고 판단한다.
#
#
# 정확한 class 번호는:
#
# print(train_data.class_indices)
#
# 로 확인할 수 있다.


# =============================================================================
# 학습 이미지 불러오기
# =============================================================================

train_data = train_datagen.flow_from_directory(

    # 학습 이미지가 저장되어 있는 최상위 폴더
    path_train,


    # -------------------------------------------------------------------------
    # target_size=(150, 150)
    # -------------------------------------------------------------------------
    # 원본 이미지 크기가 서로 달라도
    # 전부 150 x 150 크기로 resize한다.
    #
    # 예:
    #
    # 512 x 512
    # 300 x 250
    # 1024 x 768
    #
    #       ↓
    #
    # 모두 150 x 150
    #
    target_size=(150, 150),


    # -------------------------------------------------------------------------
    # batch_size=160
    # -------------------------------------------------------------------------
    # 전체 학습 데이터가 160장이기 때문에
    # 한 번에 160장을 모두 가져온다.
    #
    # 일반적으로는:
    #
    # batch_size=32
    #
    # 처럼 작은 단위로 가져오지만,
    #
    # 여기서는 최종적으로
    # 전체 데이터를 NumPy 배열로 저장해야 하기 때문에
    # 전체 이미지 수와 동일한 batch_size를 사용한다.
    #
    #
    # 따라서:
    #
    # train_data[0]
    #
    # 안에 학습 데이터 160장이 모두 들어있게 된다.
    batch_size=160,


    # -------------------------------------------------------------------------
    # class_mode='binary'
    # -------------------------------------------------------------------------
    # 클래스가 2개이므로 이진 분류
    #
    # y 데이터는 다음과 같은 형태가 된다.
    #
    # [0., 1., 0., 1., ...]
    #
    class_mode='binary',


    # -------------------------------------------------------------------------
    # color_mode='grayscale'
    # -------------------------------------------------------------------------
    # 이미지를 흑백 이미지로 읽는다.
    #
    # 따라서 이미지 한 장의 shape:
    #
    # (150, 150, 1)
    #
    # 마지막 1은 채널(channel)의 수이다.
    #
    # RGB였다면:
    #
    # (150, 150, 3)
    #
    # 이 된다.
    color_mode='grayscale',


    # -------------------------------------------------------------------------
    # shuffle=True
    # -------------------------------------------------------------------------
    # 학습 데이터 순서를 랜덤하게 섞는다.
    #
    # 단, 이미지 x와 정답 y의 대응관계는 같이 섞이므로
    # 정답이 틀어지는 것은 아니다.
    #
    # 예:
    #
    # 원래:
    #
    # image1 -> 0
    # image2 -> 1
    # image3 -> 0
    #
    # shuffle 후:
    #
    # image3 -> 0
    # image1 -> 0
    # image2 -> 1
    #
    # x와 y가 하나의 쌍으로 같이 이동한다.
    shuffle=True,
)


# 실행 예:
#
# Found 160 images belonging to 2 classes.


# =============================================================================
# 테스트 이미지 불러오기
# =============================================================================

test_data = test_datagen.flow_from_directory(

    # 테스트 이미지 경로
    path_test,


    # train과 동일하게 150 x 150으로 resize
    target_size=(150, 150),


    # 테스트 데이터가 총 120장이므로
    # 한 번에 전체 데이터를 가져온다.
    batch_size=120,


    # 이진 분류
    class_mode='binary',


    # 흑백 이미지
    color_mode='grayscale',


    # 테스트 데이터는 순서를 섞지 않는다.
    #
    # 테스트에서는 나중에
    #
    # 예측 결과
    # 실제 정답
    # 원본 파일
    #
    # 을 비교할 때 순서를 유지하는 것이 편하기 때문이다.
    shuffle=False,
)


# 실행 예:
#
# Found 120 images belonging to 2 classes.


# =============================================================================
# DirectoryIterator에서 실제 NumPy 배열 꺼내기
# =============================================================================

x_train, y_train = train_data[0][0], train_data[0][1]

x_test, y_test = test_data[0][0], test_data[0][1]


# train_data 자체는 NumPy 배열이 아니다.
#
# train_data:
#
# DirectoryIterator 객체
#
#
# train_data[0]:
#
# 첫 번째 batch
#
# 구조:
#
# (
#     x 데이터,
#     y 데이터
# )
#
#
# 따라서:
#
# train_data[0][0]
#
# -> x 데이터
#
#
# train_data[0][1]
#
# -> y 데이터
#
#
# 현재 batch_size=160이고
# 전체 학습 데이터도 160장이므로:
#
# train_data[0][0]
#
# 안에는 x_train 전체가 들어간다.


# 아래처럼 간단하게 작성해도 같은 의미이다.
#
# x_train, y_train = train_data[0]
# x_test, y_test = test_data[0]


# =============================================================================
# 데이터 shape 확인
# =============================================================================

print(x_train.shape, y_train.shape)

# 예상 출력:
#
# (160, 150, 150, 1) (160,)
#
#
# x_train:
#
# 160  = 이미지 개수
# 150  = 높이
# 150  = 너비
# 1    = grayscale 채널
#
#
# y_train:
#
# (160,)
#
# 이미지 160장에 대응하는 정답 160개


print(x_test.shape, y_test.shape)

# 예상 출력:
#
# (120, 150, 150, 1) (120,)
#
#
# x_test:
#
# 테스트 이미지 120장
# 각 이미지는 150 x 150
# grayscale이므로 채널 1개


# =============================================================================
# 이미지 → NumPy 배열 변환 시간 출력
# =============================================================================

print(
    f"데이터 변환 시간 : "
    f"{round(time.time() - start_time, 2)} 초"
)

# 현재 시간에서 처음 start_time을 뺀다.
#
# 즉:
#
# 폴더 탐색
# +
# 이미지 파일 읽기
# +
# JPEG/PNG 디코딩
# +
# 이미지 resize
# +
# grayscale 변환
# +
# 0~1 rescale
# +
# NumPy 배열 생성
#
# 까지 걸린 시간을 대략 확인할 수 있다.


# =============================================================================
# 2. NumPy 배열을 NPY 파일로 저장
# =============================================================================


# NPY 파일을 저장할 폴더
np_path = './_data/brain_npy/'


# 주의:
#
# './_data/brain_npy/'
#
# 폴더가 미리 존재해야 한다.
#
# 폴더가 없다면 np.save()가 자동으로 폴더를 만들어주지는 않는다.
#
# 필요하다면:
#
# import os
# os.makedirs(np_path, exist_ok=True)
#
# 를 먼저 사용할 수 있다.


# =============================================================================
# x_train 저장
# =============================================================================

np.save(
    np_path + 'keras45_01_x_train.npy',
    arr=x_train
)

# np.save()
#
# NumPy 배열을 .npy 형식의 파일로 저장한다.
#
#
# 첫 번째 인자:
#
# 저장할 파일 경로
#
# './_data/brain_npy/keras45_01_x_train.npy'
#
#
# 두 번째 인자:
#
# arr=x_train
#
# 저장할 NumPy 배열
#
#
# 저장되는 shape:
#
# (160, 150, 150, 1)


# =============================================================================
# y_train 저장
# =============================================================================

np.save(
    np_path + 'keras45_01_y_train.npy',
    arr=y_train
)

# 학습 이미지의 정답 저장
#
# shape:
#
# (160,)
#
#
# 예:
#
# [0., 1., 1., 0., ...]


# =============================================================================
# x_test 저장
# =============================================================================

np.save(
    np_path + 'keras45_01_x_test.npy',
    arr=x_test
)

# 테스트 이미지 저장
#
# shape:
#
# (120, 150, 150, 1)


# =============================================================================
# y_test 저장
# =============================================================================

np.save(
    np_path + 'keras45_01_y_test.npy',
    arr=y_test
)

# 테스트 이미지 정답 저장
#
# shape:
#
# (120,)


# =============================================================================
# 저장 완료 메시지
# =============================================================================

print("NPY 저장 완료.")


