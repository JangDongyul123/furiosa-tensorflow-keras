# 처음 실행
# ─────────────────────────────────────────────
#
# JPG / PNG 파일
#
#      ↓
#
# flow_from_directory()
#
#      ↓
#
# 이미지 읽기
# resize
# grayscale
# rescale
#
#      ↓
#
# DirectoryIterator
#
#      ↓
#
# train_data[0]
#
#      ↓
#
# x_train / y_train
#
#      ↓
#
# NumPy 배열
#
#      ↓
#
# np.save()
#
#      ↓
#
# .npy 파일
#
#
#
# 다음 학습부터
# ─────────────────────────────────────────────
#
# .npy 파일
#
#      ↓
#
# np.load()
#
#      ↓
#
# x_train / y_train
#
#      ↓
#
# 바로 model.fit()
#
#
# 따라서 반복 실험을 할 때
# 이미지 디코딩 / resize 등의 작업을 매번 다시 하지 않아도 된다.