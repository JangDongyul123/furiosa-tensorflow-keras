# 바로 CNN 학습에 사용할 수 있다.


# =============================================================================
# 2. CNN 모델 구성
# =============================================================================

model = Sequential()

# Sequential은:
#
# 입력
# ↓
# Conv2D
# ↓
# Conv2D
# ↓
# MaxPooling
# ↓
# ...
#
# 처럼 앞 Layer의 출력이
# 다음 Layer의 입력으로 순서대로 전달되는 구조이다.


# =============================================================================
# 첫 번째 Conv Block
# =============================================================================

model.add(
    Conv2D(
        filters=64,

        # 3 x 3 크기의 필터를 사용한다.
        kernel_size=(3, 3),

        # padding='same'
        #
        # 이미지 가장자리에 padding을 추가하여
        # 출력의 가로/세로 크기를 입력과 동일하게 유지한다.
        #
        # 입력:
        #
        # (150,150,1)
        #
        # 출력:
        #
        # (150,150,64)
        padding='same',

        # ReLU 활성화 함수
        #
        # x <= 0 → 0
        # x > 0  → x
        activation='relu',

        # 첫 번째 Layer이기 때문에
        # 입력 데이터 한 장의 shape을 지정한다.
        #
        # 높이 150
        # 너비 150
        # grayscale channel 1
        input_shape=(150, 150, 1)
    )
)


# -----------------------------------------------------------------------------
# 첫 번째 Conv2D 이후
# -----------------------------------------------------------------------------
#
# 입력:
#
# (150,150,1)
#
# filters=64
#
#      ↓
#
# 출력:
#
# (150,150,64)
#
#
# 필터 하나가 하나의 Feature Map을 만들기 때문에
#
# 필터 64개
#
# → Feature Map 64개
#
# → 출력 채널 64개


# =============================================================================
# 두 번째 Conv2D
# =============================================================================

model.add(
    Conv2D(
        filters=64,
        kernel_size=(3, 3),

        # padding을 지정하지 않았기 때문에 기본값:
        #
        # padding='valid'
        #
        # 즉 padding을 추가하지 않는다.
        #
        # 출력 크기 공식:
        #
        # (입력 - Kernel) / stride + 1
        #
        # stride 기본값 = 1
        #
        # (150 - 3) / 1 + 1
        #
        # = 148
        #
        # 따라서:
        #
        # (150,150,64)
        #
        #       ↓
        #
        # (148,148,64)
        activation='relu'
    )
)


# =============================================================================
# MaxPooling
# =============================================================================

model.add(
    MaxPooling2D()
)

# 아무 옵션도 지정하지 않으면 기본적으로:
#
# pool_size=(2,2)
#
# 를 사용한다.
#
# 일반적인 기본 strides도 pool_size와 동일한 2이다.
#
#
# 2 x 2 영역에서 가장 큰 값 하나만 남긴다.
#
#
# 입력:
#
# (148,148,64)
#
#       ↓
#
# 출력:
#
# (74,74,64)
#
#
# 가로:
# 148 → 74
#
# 세로:
# 148 → 74
#
# 채널:
# 64 → 64
#
#
# 즉 공간 크기만 줄이고 채널은 유지한다.


# =============================================================================
# Dropout
# =============================================================================

model.add(
    Dropout(0.2)
)

# 학습 과정에서 출력값 중 약 20%를
# 랜덤하게 0으로 만든다.
#
# 목적:
#
# 특정 Feature나 특정 뉴런에
# 모델이 지나치게 의존하는 것을 막아
# 과적합을 완화한다.
#
#
# shape은 변하지 않는다.
#
# (74,74,64)
#
#       ↓
#
# (74,74,64)
#
#
# 중요한 점:
#
# Dropout은 학습할 때만 적용된다.
#
# model.evaluate()
# model.predict()
#
# 같은 평가/추론 단계에서는
# 모든 뉴런을 사용한다.


# =============================================================================
# 두 번째 Conv Block
# =============================================================================

model.add(
    Conv2D(
        filters=32,
        kernel_size=(3, 3),

        # same padding
        #
        # 공간 크기 유지
        #
        # 입력:
        #
        # (74,74,64)
        #
        # 출력:
        #
        # (74,74,32)
        padding='same',

        activation='relu'
    )
)


# =============================================================================
# 네 번째 Conv2D
# =============================================================================

model.add(
    Conv2D(
        filters=32,
        kernel_size=(3, 3),

        # padding 기본값 = valid
        #
        # 74 - 3 + 1
        #
        # = 72
        #
        # 출력:
        #
        # (72,72,32)
        activation='relu'
    )
)


# =============================================================================
# 두 번째 MaxPooling
# =============================================================================

model.add(
    MaxPooling2D()
)

# 입력:
#
# (72,72,32)
#
#       ↓ 2x2 MaxPooling
#
# 출력:
#
# (36,36,32)


# =============================================================================
# 두 번째 Dropout
# =============================================================================

model.add(
    Dropout(0.25)
)

# 학습 중 출력값의 약 25%를 랜덤하게 0으로 만든다.
#
# shape은 그대로:
#
# (36,36,32)


# =============================================================================
# Flatten
# =============================================================================

model.add(
    Flatten()
)

# CNN에서 나온 Feature Map:
#
# (36,36,32)
#
# 를 Dense Layer에 넣기 위해
# 1차원 벡터로 펼친다.
#
#
# 계산:
#
# 36 × 36 × 32
#
# = 41,472
#
#
# 따라서:
#
# (36,36,32)
#
#       ↓ Flatten
#
# (41472,)
#
#
# Flatten은 Weight나 Bias를 학습하지 않는다.
#
# 단순히 배열의 모양만 바꾼다.


# =============================================================================
# Dense Layer
# =============================================================================

model.add(
    Dense(
        10,
        activation='relu'
    )
)

# Flatten 결과:
#
# 41,472개의 값
#
#       ↓
#
# Dense 뉴런 10개
#
#
# 출력 shape:
#
# (10,)
#
#
# Weight 개수:
#
# 41,472 × 10
#
# = 414,720
#
#
# Bias:
#
# 10
#
#
# 총 Parameter:
#
# 414,730개


# =============================================================================
# Dense 뒤 Dropout
# =============================================================================

model.add(
    Dropout(0.2)
)

# Dense 출력 10개 중
# 학습할 때 일부를 랜덤하게 비활성화한다.
#
# 과적합 완화 목적


# =============================================================================
# 최종 출력 Layer
# =============================================================================

model.add(
    Dense(
        1,
        activation='sigmoid'
    )
)

# 이 문제는:
#
# ad / normal
#
# 두 개 클래스를 구분하는 이진분류이므로
# 출력 뉴런을 1개 사용한다.
#
#
# sigmoid는 값을:
#
# 0 ~ 1
#
# 사이로 만든다.
#
#
# 예:
#
# 0.032
# 0.283
# 0.719
# 0.981
#
#
# 일반적으로:
#
# 0.5 미만 → class 0
# 0.5 이상 → class 1
#
# 로 변환할 수 있다.


# =============================================================================
# CNN Shape 변화 전체 정리
# =============================================================================
#
# 입력
#
# (150,150,1)
#
#       ↓
#
# Conv2D(64, 3x3, same)
#
# (150,150,64)
#
#       ↓
#
# Conv2D(64, 3x3, valid)
#
# (148,148,64)
#
#       ↓
#
# MaxPooling2D
#
# (74,74,64)
#
#       ↓
#
# Dropout
#
# (74,74,64)
#
#       ↓
#
# Conv2D(32, 3x3, same)
#
# (74,74,32)
#
#       ↓
#
# Conv2D(32, 3x3, valid)
#
# (72,72,32)
#
#       ↓
#
# MaxPooling2D
#
# (36,36,32)
#
#       ↓
#
# Dropout
#
# (36,36,32)
#
#       ↓
#
# Flatten
#
# (41472,)
#
#       ↓
#
# Dense(10)
#
# (10,)
#
#       ↓
#
# Dropout
#
# (10,)
#
#       ↓
#
# Dense(1, sigmoid)
#
# (1,)


# =============================================================================
# 3. 모델 Compile
# =============================================================================

model.compile(

    # binary_crossentropy:
    #
    # 정답이 0 / 1인 이진분류에서
    # 대표적으로 사용하는 Loss 함수
    loss='binary_crossentropy',

    # Adam Optimizer:
    #
    # 역전파를 통해 계산한 Gradient를 사용하여
    # Weight와 Bias를 업데이트한다.
    optimizer='adam',

    # 학습하면서 accuracy도 함께 계산
    metrics=['acc']
)


# =============================================================================
# EarlyStopping 설정
# =============================================================================

early_stopping = EarlyStopping(

    # 학습 데이터 accuracy가 아니라
    # validation 데이터의 accuracy를 감시한다.
    #
    # model.fit()에서 validation_split=0.3을 사용하므로
    # val_acc가 생성된다.
    monitor='val_acc',

    # accuracy는 높을수록 좋은 값이다.
    #
    # 따라서 최대값을 찾는다.
    mode='max',

    # val_acc가 더 이상 좋아지지 않아도
    # 130 epoch까지 기다린다.
    patience=130,

    # 학습 종료 후
    # 마지막 epoch의 Weight를 사용하는 것이 아니라
    #
    # val_acc가 가장 좋았던 epoch의 Weight를 복원한다.
    restore_best_weights=True,

    # EarlyStopping 관련 메시지를 출력한다.
    verbose=1
)


# =============================================================================
# epochs와 patience 관계
# =============================================================================
#
# 현재 설정:
#
# epochs=200
# patience=130
#
# 이므로 EarlyStopping은 동작할 수는 있다.
#
#
# 예를 들어:
#
# Epoch 20에서 최고 val_acc 기록
#
# 이후 계속 개선되지 않음
#
#       ↓
#
# 130번 기다림
#
#       ↓
#
# 약 Epoch 150 근처에서 EarlyStopping 가능
#
#
# 하지만 patience=130은 굉장히 큰 값이다.
#
# 데이터가 160장으로 매우 적기 때문에
# validation accuracy가 흔들릴 가능성이 크다는 이유로
# 수업에서 크게 잡았을 수도 있지만,
#
# 일반적인 실험에서는:
#
# patience=10
# patience=20
#
# 정도처럼 더 작게 설정하는 경우가 많다.


# =============================================================================
# 훈련 시간 측정 시작
# =============================================================================

start_time_train = time.time()


# =============================================================================
# 모델 학습
# =============================================================================

model.fit(

    # 학습용 이미지
    x_train,

    # 정답
    y_train,

    # 전체 Dataset을 최대 200번 반복
    epochs=200,

    # Gradient를 한 번 계산하고
    # Weight를 한 번 업데이트할 때
    # 13개의 데이터를 사용한다.
    batch_size=13,

    # x_train의 30%를 validation용으로 분리한다.
    validation_split=0.3,

    # EarlyStopping 적용
    callbacks=[early_stopping],

    # 학습 과정을 화면에 출력
    verbose=1
)


# =============================================================================
# validation_split=0.3
# =============================================================================
#
# 전체 학습 데이터:
#
# 160장
#
#
# 그중 약 70%:
#
# 실제 Weight 학습에 사용
#
# 약:
#
# 160 × 0.7
# = 112장
#
#
# 약 30%:
#
# Validation
#
# 약:
#
# 160 × 0.3
# = 48장
#
#
# 따라서 대략:
#
# Training:
# 112장
#
# Validation:
# 48장
#
#
# Validation 데이터에서는:
#
# Forward Propagation
# ↓
# val_loss / val_acc 계산
#
# 까지만 한다.
#
# Backpropagation으로 Weight를 수정하지 않는다.


# =============================================================================
# batch_size=13의 의미
# =============================================================================
#
# 실제 학습 데이터가 약 112장이고
#
# batch_size=13
#
# 이라면:
#
# 13장
# ↓
# Forward
# ↓
# Loss
# ↓
# Backpropagation
# ↓
# Weight 수정 1회
#
#
# 다음 13장
