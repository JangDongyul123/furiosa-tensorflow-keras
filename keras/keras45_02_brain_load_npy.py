import numpy as np
import time

# Sequential:
# 레이어를 위에서 아래 순서대로 쌓는 방식의 모델
from tensorflow.keras.models import Sequential

# Dense         : 완전연결층
# Conv2D        : 이미지의 특징을 추출하는 합성곱층
