import numpy as np

# ImageDataGenerator
# - 이미지 데이터를 모델에 넣기 전에 전처리하거나
# - 이미지의 위치/각도/크기 등을 랜덤하게 변형하여
#   데이터 증강(Data Augmentation)을 수행할 수 있는 클래스
#
# 예:
# 원본 이미지 1장
#   ↓
# 좌우 반전 / 회전 / 이동 / 확대 등의 변형
#   ↓
# 모델은 같은 이미지라도 조금씩 다른 형태로 학습하게 됨
#
# 주의:
# 실제 이미지 파일 자체를 새로 저장해서 개수를 늘리는 것이 아니라
# 이미지를 가져올 때 실시간으로 변형해서 모델에게 전달한다.
from tensorflow.keras.preprocessing.image import ImageDataGenerator


# =============================================================================
# 1. 학습용 이미지 전처리 + 데이터 증강 설정
# =============================================================================

train_datagen = ImageDataGenerator(

    # -------------------------------------------------------------------------
    # rescale
    # -------------------------------------------------------------------------
    # 이미지의 픽셀값은 일반적으로 0 ~ 255 범위이다.
    #
    # 예:
    # 0   -> 검정색
    # 255 -> 흰색
    #
    # 1/255를 곱하면
    #
    # 0   -> 0.0
    # 128 -> 약 0.502
    # 255 -> 1.0
    #
    # 즉, 픽셀값을 0 ~ 1 범위로 스케일링한다.
    #
    # rescale은 "데이터 증강"이 아니라 "스케일링"이다.
    rescale=1./255,


    # -------------------------------------------------------------------------
    # horizontal_flip
    # -------------------------------------------------------------------------
    # 이미지를 좌우로 랜덤하게 뒤집는다.
    #
    # 원본:
    #     사람 →
    #
    # 변환:
    #     ← 사람
    #
    # True라고 해서 반드시 모든 이미지를 뒤집는 것이 아니라,
    # 이미지를 불러올 때 랜덤하게 좌우 반전을 적용한다.
    #
    # 좌우로 뒤집어도 정답이 바뀌지 않는 이미지에 사용해야 한다.
    horizontal_flip=True,


    # -------------------------------------------------------------------------
    # vertical_flip
    # -------------------------------------------------------------------------
    # 이미지를 위아래로 랜덤하게 뒤집는다.
    #
    # 원본
    #   ↓
    # 상하 반전
    #
    # 주의:
    # 데이터 종류에 따라 위험할 수 있다.
    #
    # 예를 들어 사람 사진이나 의료 영상처럼
    # 위/아래 방향 자체가 의미를 가지는 데이터라면
    # 실제 데이터에서는 존재하기 어려운 이미지를 만들 수도 있다.
    vertical_flip=True,


    # -------------------------------------------------------------------------
    # width_shift_range
    # -------------------------------------------------------------------------
    # 이미지를 좌우 방향으로 랜덤하게 이동시킨다.
    #
    # 0.1은 이미지 너비의 최대 약 10% 범위 안에서 이동한다는 의미이다.
    #
    # 이미지 너비가 100이라면
    # 약 10픽셀 정도 범위 내에서 좌우 이동이 가능하다.
    #
    # 예:
    #
    #       ○
    #
    #          ↓ 오른쪽 이동
    #
    #             ○
    #
    width_shift_range=0.1,


    # -------------------------------------------------------------------------
    # height_shift_range
    # -------------------------------------------------------------------------
    # 이미지를 위/아래 방향으로 랜덤하게 이동시킨다.
    #
    # 0.1이면 이미지 높이의 최대 약 10% 범위 내에서 이동한다.
    #
    # target_size=(100, 100)이므로
    # 약 10픽셀 정도 범위에서 이동될 수 있다.
    height_shift_range=0.1,


    # -------------------------------------------------------------------------
    # rotation_range
    # -------------------------------------------------------------------------
    # 이미지를 랜덤하게 회전시킨다.
    #
    # rotation_range=5
    #
    # 대략 -5도 ~ +5도 범위에서 랜덤하게 회전한다.
    #
    # 즉,
    #
    # -5도
    # -2도
    #  0도
    # +3도
    # +5도
    #
    # 같은 형태의 회전이 발생할 수 있다.
    #
    # "정확히 5도 회전"이 아니라
    # 최대 회전 범위를 지정하는 것이다.
    rotation_range=5,


    # -------------------------------------------------------------------------
    # zoom_range
    # -------------------------------------------------------------------------
    # 이미지를 랜덤하게 확대하거나 축소한다.
    #
    # zoom_range=1.2는 확대/축소 변형 범위를 설정한다.
    #
    # 학습할 때 항상 동일한 크기로만 물체가 등장하는 것이 아니라
    # 조금 더 크게 보이거나 작게 보이는 상황에도
    # 모델이 대응하도록 만들기 위한 목적이다.
    #
    # 예:
    #
    #      ○
    #
    #      ↓ 확대
    #
    #     OOO
    #
    zoom_range=1.2,


    # -------------------------------------------------------------------------
    # shear_range
    # -------------------------------------------------------------------------
    # 이미지에 전단 변환(Shear Transformation)을 적용한다.
    #
    # 쉽게 말하면 이미지를 한 방향으로 비스듬하게 밀어서
    # 기울어진 것처럼 만드는 변환이다.
    #
    # 예:
    #
    # 원래 사각형
    #
    # ┌─────┐
    # │     │
    # └─────┘
    #
    # shear 적용
    #
    #   /─────/
    #  /     /
    # /─────/
    #
    # 즉, 단순히 이미지를 "회전"시키는 것과는 다르다.
    shear_range=0.7,


    # -------------------------------------------------------------------------
    # fill_mode
    # -------------------------------------------------------------------------
    # 이미지를 회전하거나 이동시키면
    # 원래 이미지가 없었던 빈 공간이 생길 수 있다.
    #
    # 예:
    #
    # 원본
    #
    # █████
    # █████
    #
    # 오른쪽으로 이동
    #
    # ??█████
    # ??█████
    #
    # 여기서 ?? 부분을 어떤 값으로 채울 것인지 결정한다.
    #
    # 'nearest'
    # -> 가장 가까이에 있는 픽셀값을 복사하여 빈 공간을 채운다.
    #
    # 따라서 갑자기 검은색 공간이 생기는 것을 어느 정도 방지한다.
    fill_mode='nearest',
)


# =============================================================================
# 2. 테스트 데이터 전처리
# =============================================================================

# 테스트 데이터에는 일반적으로 데이터 증강을 사용하지 않는다.
#
# 이유:
# 테스트 데이터는
# "실제 모델 성능을 평가하기 위한 원본 데이터"이기 때문이다.
#
# 학습 데이터:
#   스케일링 + 데이터 증강
#
# 테스트 데이터:
#   스케일링만 수행
#
# 단, train과 test의 스케일링 방식은 반드시 동일해야 한다.
test_datagen = ImageDataGenerator(
    rescale=1./255
)


# =============================================================================
# 3. 이미지가 저장되어 있는 폴더 경로
# =============================================================================

path_train = './_data/image/brain/train/'
path_test = './_data/image/brain/test/'


# 폴더 구조는 일반적으로 다음과 같이 되어 있다고 보면 된다.
#
# brain/
#
# ├── train/
# │   ├── ad/
# │   │   ├── image001.jpg
# │   │   ├── image002.jpg
# │   │   └── ...
# │   │
# │   └── normal/
# │       ├── image001.jpg
# │       ├── image002.jpg
# │       └── ...
# │
# └── test/
#     ├── ad/
#     └── normal/
#
#
# flow_from_directory()는
# 하위 폴더 이름을 보고 자동으로 class를 구분한다.
#
# 예:
#
# train/
# ├── ad/
# └── normal/
#
# 와 같은 구조라면
#
# ad     -> 0
# normal -> 1
#
# 처럼 자동으로 정수 라벨을 만든다.
#
# 실제 어떤 클래스가 0이고 1인지는
#
# print(xy_train.class_indices)
#
# 로 확인하는 것이 가장 정확하다.


# =============================================================================
# 4. 학습 데이터 생성
# =============================================================================

xy_train = train_datagen.flow_from_directory(

    # -------------------------------------------------------------------------
    # directory
    # -------------------------------------------------------------------------
    # 학습 이미지가 들어있는 최상위 폴더
    #
    # 이 폴더 바로 아래에 class별 폴더가 있어야 한다.
    #
    # 예:
    # train/ad/
    # train/normal/
    path_train,


    # -------------------------------------------------------------------------
    # target_size
    # -------------------------------------------------------------------------
    # 모든 이미지의 크기를 (100, 100)으로 통일한다.
    #
    # 원본 이미지 크기가
    #
    # 300 x 300
    # 512 x 512
    # 700 x 500
    #
    # 처럼 각각 달라도
    #
    # 모델에 넣기 전에 모두
    #
    # 100 x 100
    #
    # 크기로 resize한다.
    #
    # 여기에는 채널 크기는 적지 않는다.
    target_size=(100, 100),


    # -------------------------------------------------------------------------
    # batch_size
    # -------------------------------------------------------------------------
    # 이미지를 한 번에 몇 장씩 가져올 것인지 결정한다.
    #
    # 전체 이미지가 160장이고
    # batch_size=10이면
    #
    # 1번째 batch : 10장
    # 2번째 batch : 10장
    # ...
    # 16번째 batch : 10장
    #
    # 총 16개의 batch가 만들어진다.
    #
    # 즉,
    #
    # 160 / 10 = 16 batch
    batch_size=10,


    # -------------------------------------------------------------------------
    # class_mode
    # -------------------------------------------------------------------------
    # 정답 y를 어떤 형태로 만들지 결정한다.
    #
    # binary:
    # 2개의 클래스를 0 또는 1 형태로 만든다.
    #
    # 예:
    #
    # ad     -> 0
    # normal -> 1
    #
    # y:
    #
    # [0., 1., 1., 0., 0., ...]
    #
    # 이진 분류에서 주로 사용한다.
    class_mode='binary',


    # -------------------------------------------------------------------------
    # color_mode
    # -------------------------------------------------------------------------
    # 이미지를 어떤 채널 형태로 읽을지 결정한다.
    #
    # grayscale:
    # 흑백 이미지
    #
    # 이미지 한 장의 shape:
    #
    # (100, 100, 1)
    #
    # 100 : 세로
    # 100 : 가로
    # 1   : 채널
    #
    # RGB 컬러 이미지라면 채널이 3이므로
    #
    # (100, 100, 3)
    #
    # 이 된다.
    color_mode='grayscale',


    # -------------------------------------------------------------------------
    # shuffle
    # -------------------------------------------------------------------------
    # 매 epoch마다 학습 이미지의 순서를 섞는다.
    #
    # 예:
    #
    # 원래
    # 1 2 3 4 5
    #
    # shuffle
    # 3 1 5 2 4
    #
    # 학습에서는 특정 순서에 모델이 영향을 받지 않도록
    # 일반적으로 shuffle=True를 사용한다.
    shuffle=True,
)


# flow_from_directory 실행 시 예:
#
# Found 160 images belonging to 2 classes.
#
# 의미:
#
# 총 이미지 수 : 160장
# 클래스 수     : 2개


# =============================================================================
# 5. 테스트 데이터 생성
# =============================================================================

xy_test = test_datagen.flow_from_directory(

    # 테스트 이미지 경로
    path_test,

    # train과 동일한 크기로 맞춰준다.
    target_size=(100, 100),

    # 한 번에 10장씩 가져온다.
    batch_size=10,

    # ad / normal 두 클래스이므로 이진 분류
    class_mode='binary',

    # train과 동일하게 흑백으로 읽는다.
    color_mode='grayscale',

    # 테스트에서는 일반적으로 섞지 않는다.
    #
    # 특히 나중에
    #
    # model.predict()
    #
    # 결과와 실제 정답 또는 파일명을 비교할 때
    # 순서가 유지되어야 해석하기 쉽다.
    shuffle=False,
)


# 실행 예:
#
# Found 120 images belonging to 2 classes.
#
# 총 120장의 테스트 이미지가 있다는 의미


# =============================================================================
# 6. xy_train의 정체 확인
# =============================================================================

print(xy_train)

# 출력 예:
#
# <keras.preprocessing.image.DirectoryIterator object at 0x...>
#
# xy_train은 numpy 배열 그 자체가 아니다.
#
# 이미지 파일을
#
# "필요할 때마다 batch 단위로 읽어서 반환해주는 객체"
#
# 즉, DirectoryIterator이다.
#
# 구조를 단순하게 표현하면:
#
# xy_train
#    │
#    ├── batch 0
#    │     ├── x 데이터 10장
#    │     └── y 라벨 10개
#    │
#    ├── batch 1
#    │     ├── x 데이터 10장
#    │     └── y 라벨 10개
#    │
#    └── ...


# =============================================================================
# 7. next()를 사용해서 다음 batch 하나 가져오기
# =============================================================================

print(xy_train.next())

# batch_size=10이므로
# 다음 데이터 10장과 그에 해당하는 y 10개가 나온다.
#
# 형태:
#
# (
#     x 데이터,
#     y 데이터
# )
#
# 즉, tuple 형태이다.
#
#
# 예:
#
# (
#   array([이미지 10장]),
#
#   array([
#       1.,
#       0.,
#       0.,
#       1.,
#       ...
#   ])
# )
#
#
# x shape:
#
# (10, 100, 100, 1)
#
# 의미:
#
# 10  = batch_size, 이미지 10장
# 100 = 이미지 높이
# 100 = 이미지 너비
# 1   = grayscale 채널
#
#
# y shape:
#
# (10,)
#
# 이미지 10장 각각에 대한 정답이 10개 존재


# =============================================================================
