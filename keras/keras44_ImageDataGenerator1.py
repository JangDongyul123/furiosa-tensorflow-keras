#
# <class 'numpy.ndarray'>
#
# 실제 정답 데이터 y도 numpy 배열이다.


# =============================================================================
# 10. 전체 구조 최종 정리
# =============================================================================
#
# xy_train
#
# DirectoryIterator
#
#            xy_train
#                │
#                │
#        ┌───────┴───────┐
#        │               │
#    batch 0          batch 1 ...
#        │
#        │
#   xy_train[0]
#        │
#        ├────────────────────────┐
#        │                        │
# xy_train[0][0]            xy_train[0][1]
#        │                        │
#        x                        y
#        │                        │
# numpy.ndarray              numpy.ndarray
#        │                        │
# (10,100,100,1)                (10,)
#
#
# 핵심:
#
# xy_train[배치번호][0] = x 데이터
# xy_train[배치번호][1] = y 데이터
#
#
# 예:
#
# xy_train[0][0]  -> 첫 번째 batch의 이미지 10장
# xy_train[0][1]  -> 첫 번째 batch의 정답 10개
#
# xy_train[1][0]  -> 두 번째 batch의 이미지 10장
# xy_train[1][1]  -> 두 번째 batch의 정답 10개
#
#
# 전체 데이터 160장이고 batch_size=10이라면:
#
# len(xy_train) = 16
#
# 사용 가능한 batch index:
#
# 0 ~ 15
#
# 따라서:
#
# xy_train[16]
#
# 을 호출하면 존재하지 않는 17번째 batch를 요청하는 것이므로
# 오류가 발생한다.