# xy_train[0]
#
# -> 첫 번째 batch 전체
#
# 구조:
#
# xy_train[0]
#      │
#      ├── [0] : x
#      └── [1] : y


print(xy_train[0][0].shape)

# xy_train[0]
# -> 첫 번째 batch
#
