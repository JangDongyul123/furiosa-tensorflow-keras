# =================================================================================
# 2. train / test 분리
# =================================================================================

'''
현재 y는 아직 원-핫 인코딩 전이다.

예:

y = [0, 0, 0, ..., 1, 1, 1, ..., 2, 2, 2]


=================================================================================
stratify=y
=================================================================================

stratify=y의 의미:

원래 y에 존재하는 클래스 비율을
train과 test에서도 최대한 동일하게 유지하면서 데이터를 나눈다.


Iris 데이터는

0 : 50개
1 : 50개
2 : 50개

로 모든 클래스가 동일한 비율이다.


80 : 20으로 나누면

train:

0 : 40개
1 : 40개
2 : 40개


test:

0 : 10개
1 : 10개
2 : 10개

가 된다.


즉,

stratify의 목적은

"클래스 비율을 유지하여 데이터를 나누는 것"

이다.


반면 원-핫 인코딩의 목적은

"정답의 표현 방식을 바꾸는 것"

이다.


예:

클래스 번호

0
1
2

를

0 → [1, 0, 0]
1 → [0, 1, 0]
2 → [0, 0, 1]

형태로 바꾸는 것이 원-핫 인코딩이다.


따라서 일반적으로

데이터 분할
    ↓
원-핫 인코딩

순서로 처리하면
각 작업의 역할이 명확하다.
'''


x_train, x_test, y_train, y_test = train_test_split(
    x,
    y,
    train_size=0.8,
    random_state=66,
    shuffle=True,
    stratify=y
)


print(x_train.shape, x_test.shape)
# (120, 4), (30, 4)

print(y_train.shape, y_test.shape)
# (120,), (30,)


print("y_train 클래스 개수")
print(np.unique(y_train, return_counts=True))

print("y_test 클래스 개수")
print(np.unique(y_test, return_counts=True))

