'''
=================================================================================
EarlyStopping
=================================================================================

monitor='val_loss'

→ validation loss를 관찰한다.


patience=10

→ val_loss가 더 좋아지지 않는 상태가
   일정 기간 지속되면 학습을 중단한다.


주의:

patience=10은 단순히

"무조건 10 epoch 뒤 종료"

라는 뜻이 아니다.

val_loss의 개선 여부를 관찰하면서
개선되지 않는 상태가 지속될 때 종료한다.


mode='auto'

→ monitor에 설정된 지표를 보고
   증가하는 방향이 좋은지
   감소하는 방향이 좋은지
   Keras가 자동으로 판단한다.

val_loss는 작을수록 좋으므로
최소값 방향으로 판단한다.


restore_best_weights=True

→ 학습이 끝난 마지막 epoch의 가중치를 쓰는 것이 아니라

학습 과정 중

val_loss가 가장 좋았던 시점의 모델 가중치

로 복원한다.
'''


# =================================================================================
