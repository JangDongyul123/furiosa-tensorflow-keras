'''
Iris 데이터는 입력 feature가 4개이다.

예:

sepal length
sepal width
petal length
petal width


따라서 한 샘플의 shape은

(4,)

이다.


주의:

(4)

는 그냥 정수 4이다.


(4,)

는 원소 하나를 가진 tuple이다.
'''


model = Sequential()


# 입력 데이터의 feature가 4개
model.add(
    Input(
        shape=(4,)
    )
)


# 첫 번째 은닉층
model.add(
    Dense(
        1000,
        activation='relu'
    )
)


# 두 번째 은닉층
model.add(
    Dense(
        1000,
        activation='relu'
    )
)


# 세 번째 은닉층
model.add(
    Dense(
        1000,
        activation='relu'
    )
)


# 출력층
model.add(
    Dense(
        3,
        activation='softmax'
    )
)


'''
=================================================================================
Dense(1000)
=================================================================================

Dense(1000, activation='relu')

에서

1000은 해당 층의 뉴런 개수이다.


주의:

Dense(1000)

처럼 activation을 생략하면
기본 activation은 linear이다.


즉

Dense(1000)

은 사실상

Dense(
    1000,
    activation='linear'
)

과 같다.


이번 코드에서는 은닉층에 ReLU를 사용하려는 목적이므로

모든 은닉층에

activation='relu'

를 명시하였다.


=================================================================================
출력층의 뉴런이 3개인 이유
=================================================================================

Iris의 클래스가

0
1
2

총 3개이기 때문이다.


따라서 출력층은

Dense(
    3,
    activation='softmax'
)

를 사용한다.


각 뉴런은 하나의 클래스에 대응한다.


출력:

[
    class 0 점수,
    class 1 점수,
    class 2 점수
]


=================================================================================
Softmax
=================================================================================

softmax는 다중분류의 출력층에서
주로 사용하는 활성화 함수이다.


Dense(3)에서 softmax 적용 전 값이

[2.0, 1.0, 0.1]

이라고 하자.


이러한 softmax 적용 전 값을
logit이라고 부르기도 한다.


softmax를 적용하면 대략

[0.659, 0.242, 0.099]

가 된다.


각 값은 0 ~ 1 사이이고

0.659 + 0.242 + 0.099 ≈ 1

이므로

모든 출력값의 합이 1이 된다.


일반적으로 이 값을
각 클래스에 대한 확률처럼 해석한다.


=================================================================================
중요
=================================================================================

softmax 자체가

[0.659, 0.242, 0.099]

를

[1, 0, 0]

으로 바꾸는 것은 아니다.


softmax의 출력은 그대로

[0.659, 0.242, 0.099]

이다.


최종적으로 어떤 클래스를 예측했는지 선택하려면

가장 큰 값의 index를 찾는

argmax

를 사용한다.


np.argmax(
    [0.659, 0.242, 0.099]
)

→ 0


따라서

class 0

을 예측한 것으로 판단한다.


=================================================================================
같은 최대값이 존재한다면?
=================================================================================

softmax 적용 전 값이

[2.0, 2.0, 0.1]

이라면

softmax 결과도 대략

[0.465, 0.465, 0.070]

처럼 앞의 두 값이 동일해진다.


np.argmax()

는 최대값이 여러 개 존재하면

"가장 먼저 등장한 최대값의 index"

를 반환한다.


따라서

np.argmax(
    [0.465, 0.465, 0.070]
)

결과는

0

이다.
'''


