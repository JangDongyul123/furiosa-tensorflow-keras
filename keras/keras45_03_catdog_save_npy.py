import numpy as np
import time

# ImageDataGenerator
# - 폴더에 저장된 JPG/PNG 이미지 파일을 읽어올 수 있음
# - 이미지 크기 변경
# - 픽셀값 스케일링
# - 데이터 증강
# 등을 수행할 수 있는 Keras 클래스
from tensorflow.keras.preprocessing.image import ImageDataGenerator


# =============================================================================
# 1. Cat & Dog 이미지 데이터를 NumPy 배열로 변환 후 NPY 파일로 저장
# =============================================================================
#
# 이 코드의 목적:
#
# 원본 JPG 이미지를 매번 학습할 때마다 다시 읽으면:
#
# JPG 파일 읽기
#       ↓
# JPEG 압축 해제(디코딩)
#       ↓
# 이미지 resize
#       ↓
# RGB 배열 생성
#       ↓
# 0~1 스케일링
#       ↓
# NumPy 배열 생성
#
# 과정을 매번 반복해야 한다.
#
#
# 그래서 위 과정을 한 번만 수행한 뒤
# 결과를 .npy 파일로 저장해두면:
#
# 다음 학습부터
#
# .npy
#   ↓
# np.load()
#   ↓
# 바로 x_train / y_train
#
# 형태로 빠르게 불러올 수 있다.
#
#
# 주의:
# NPY 저장은 "RAM 메모리를 절약하는 방법"이라고 보기는 어렵다.
#
# 오히려 현재 코드는 모든 이미지 8005장을 한 번에
# NumPy 배열로 만들기 때문에 RAM 사용량이 매우 크다.
#
# NPY의 주요 장점은:
#
# - JPG를 매번 디코딩하지 않아도 됨
# - resize를 매번 하지 않아도 됨
# - rescale을 매번 하지 않아도 됨
# - 반복 실험 시 데이터 로딩 속도가 빨라짐
#
# 즉:
#
# "메모리 절약"
#
# 보다는
#
# "반복적인 이미지 전처리 및 I/O 시간 절약"
#
# 이 핵심 목적이다.


# =============================================================================
# 이미지 → NumPy 배열 변환 시간 측정 시작
# =============================================================================

start_time = time.time()

# 현재 시간을 초 단위 숫자로 저장한다.
#
# 나중에:
#
# time.time() - start_time
#
# 을 계산하면
#
# 이미지 읽기
# + resize
# + RGB 변환
# + rescale
# + NumPy 배열 생성
#
# 에 걸린 시간을 확인할 수 있다.


# =============================================================================
# ImageDataGenerator 생성
# =============================================================================

train_datagen = ImageDataGenerator(
    rescale=1./255
)

test_datagen = ImageDataGenerator(
    rescale=1./255
)


# 이미지의 픽셀값은 일반적으로:
#
# 0 ~ 255
#
# 범위이다.
#
#
# rescale=1./255
#
# 를 적용하면:
#
# 0   -> 0.0
# 128 -> 약 0.502
# 255 -> 1.0
#
#
# 따라서 픽셀값의 범위를:
#
# 0 ~ 255
#
#       ↓
#
# 0 ~ 1
#
# 로 바꾼다.
#
#
# 현재 코드에서는:
#
# horizontal_flip
# rotation_range
# width_shift_range
# zoom_range
#
# 등의 옵션을 사용하지 않으므로
# 데이터 증강(Data Augmentation)은 하지 않는다.
#
# 단순히 스케일링만 수행한다.


# =============================================================================
# 이미지 데이터 경로
# =============================================================================

path_train = './_data/image/cat-dog/training_set/'
path_test = './_data/image/cat-dog/test_set/'


# 폴더 구조는 대략 다음과 같다고 보면 된다.
#
#
# cat-dog/
#
# ├── training_set/
# │
# │   ├── cats/
# │   │   ├── cat.1.jpg
# │   │   ├── cat.2.jpg
# │   │   └── ...
# │   │
# │   └── dogs/
# │       ├── dog.1.jpg
# │       ├── dog.2.jpg
# │       └── ...
# │
# └── test_set/
#
#     ├── cats/
#     │   └── ...
#     │
#     └── dogs/
#         └── ...
#
#
# flow_from_directory()는
# 하위 폴더 이름을 보고 자동으로 class를 만든다.
#
# 예:
#
# cats/
# dogs/
#
# 라면 일반적으로:
#
# cats -> 0
# dogs -> 1
#
# 로 라벨이 지정된다.
#
#
# 정확한 클래스 번호는:
#
# print(train_data.class_indices)
#
# 로 확인하는 것이 가장 정확하다.


# =============================================================================
# 학습 데이터 불러오기
# =============================================================================

train_data = train_datagen.flow_from_directory(

    # -------------------------------------------------------------------------
    # directory
    # -------------------------------------------------------------------------
    # 학습 이미지가 들어있는 최상위 폴더
    path_train,


    # -------------------------------------------------------------------------
    # target_size=(100, 100)
    # -------------------------------------------------------------------------
    # 원본 이미지 크기가 서로 달라도
    # 모두 100 x 100 크기로 resize한다.
    #
    # 예:
    #
    # 300 x 200
    # 500 x 500
    # 1024 x 768
    #
    #       ↓
    #
    # 모두:
    #
    # 100 x 100
    #
    # CNN에 넣으려면 각 이미지의 크기를
    # 동일하게 맞춰줄 필요가 있다.
    target_size=(100, 100),


    # -------------------------------------------------------------------------
    # batch_size=8005
    # -------------------------------------------------------------------------
    # DirectoryIterator가 한 번에 반환할 이미지 수이다.
    #
    # 현재 학습 이미지 전체가 8005장이므로:
    #
    # batch_size=8005
    #
    # 로 설정하면 전체 이미지를 한 번에 가져온다.
    #
    #
    # 따라서:
    #
    # train_data[0]
    #
    # 안에 전체 8005장의 학습 데이터가 들어간다.
    #
    #
    # 일반적인 사용:
    #
    # batch_size=32
    #
    # 32장
    # ↓
    # 다음 32장
    # ↓
    # 다음 32장
    #
    #
    # 현재 코드:
    #
    # batch_size=8005
    #
    # 8005장 전부
    # ↓
    # RAM에 한 번에 올림
    #
    #
    # 따라서 메모리 사용량이 매우 커질 수 있다.
    batch_size=8005,


    # -------------------------------------------------------------------------
    # class_mode='binary'
    # -------------------------------------------------------------------------
    # Cat / Dog 두 개의 클래스를 구분하는
    # 이진분류 문제이므로 binary를 사용한다.
    #
    # y의 예:
    #
    # [0., 1., 0., 1., 1., ...]
    #
    # 정확히 어떤 클래스가 0/1인지는
    # train_data.class_indices를 확인해야 한다.
    class_mode='binary',


    # -------------------------------------------------------------------------
    # color_mode='rgb'
    # -------------------------------------------------------------------------
    # 이미지를 RGB 컬러 이미지로 읽는다.
    #
    # 따라서 이미지 한 장의 shape은:
    #
    # (100, 100, 3)
    #
    # 마지막 3:
    #
    # Red
    # Green
    # Blue
    #
    # 3개의 채널을 의미한다.
    #
    #
    # grayscale이었다면:
    #
    # (100, 100, 1)
    #
    # 이 된다.
    color_mode='rgb',


    # -------------------------------------------------------------------------
    # shuffle=True
    # -------------------------------------------------------------------------
    # 이미지 순서를 무작위로 섞는다.
    #
    # 단:
    #
    # x 이미지와 y 정답은 함께 움직인다.
    #
    # 즉 정답과 이미지의 대응관계가 깨지지는 않는다.
    #
    # 예:
    #
    # 원래:
    #
    # cat1 -> 0
    # dog1 -> 1
    # cat2 -> 0
    #
    #
    # shuffle 후:
    #
    # dog1 -> 1
    # cat2 -> 0
    # cat1 -> 0
    #
    #
    # 이런 식으로 x와 y 쌍이 같이 섞인다.
    shuffle=True,
)


# 실행 시 예:
#
# Found 8005 images belonging to 2 classes.


# =============================================================================
# 테스트 데이터 불러오기
# =============================================================================

test_data = test_datagen.flow_from_directory(

    # 테스트 이미지 폴더
    path_test,


    # Train 데이터와 동일하게
    # 모든 이미지를 100 x 100으로 resize
    target_size=(100, 100),


    # 테스트 데이터 전체가 2023장이므로
    # 한 번에 전체 테스트 이미지를 가져온다.
    batch_size=2023,


    # Cat / Dog 이진분류
    class_mode='binary',


    # RGB 컬러 이미지
    color_mode='rgb',


    # 테스트 데이터는 순서를 섞지 않는다.
    #
    # 이후:
    #
    # model.predict()
    #
    # 의 결과와
    #
    # 실제 파일 이름
    # 실제 y 정답
    #
    # 을 비교하기 쉽도록 순서를 유지한다.
    shuffle=False,
)


# 실행 시 예:
#
# Found 2023 images belonging to 2 classes.


# =============================================================================
# DirectoryIterator에서 실제 NumPy 배열 꺼내기
# =============================================================================

x_train, y_train = train_data[0][0], train_data[0][1]

x_test, y_test = test_data[0][0], test_data[0][1]


# train_data 자체는 NumPy 배열이 아니라:
#
# DirectoryIterator 객체
#
# 이다.
#
#
# 구조:
#
# train_data
#
#     ↓
#
# batch 0
#
#     ↓
#
# train_data[0]
#
#     ↓
#
# (
#     x 데이터,
#     y 데이터
# )
#
#
# 따라서:
#
# train_data[0][0]
#
# = 첫 번째 batch의 x 데이터
#
#
# train_data[0][1]
#
# = 첫 번째 batch의 y 데이터
#
#
# 현재 batch_size가 전체 데이터 개수와 같으므로:
#
# train_data[0][0]
#
# 안에 학습 이미지 전체 8005장이 들어간다.


# 위 코드는 사실 아래처럼 작성해도 같다.
#
# x_train, y_train = train_data[0]
# x_test, y_test = test_data[0]


# =============================================================================
# 예상 Shape
# =============================================================================
#
# x_train:
#
# (8005, 100, 100, 3)
#
# 8005 = 학습 이미지 개수
# 100  = 높이
# 100  = 너비
# 3    = RGB 채널
#
#
# y_train:
#
# (8005,)
#
#
# x_test:
#
# (2023, 100, 100, 3)
#
#
# y_test:
#
# (2023,)


# shape도 실제로 확인하고 싶다면:
#
# print(x_train.shape, y_train.shape)
# print(x_test.shape, y_test.shape)


# =============================================================================
# 메모리 사용량 계산
# =============================================================================
#
# x_train의 원소 개수:
#
# 8005 × 100 × 100 × 3
#
# = 240,150,000개
#
#
# rescale 이후 일반적으로 float32이므로
# 숫자 하나가 4 byte라면:
#
# 240,150,000 × 4 byte
#
# = 960,600,000 byte
#
# ≈ 약 960 MB
#
# ≈ 약 916 MiB
#
#
# 즉:
#
# x_train 하나만 거의 1GB이다.
#
#
# x_test까지 계산하면:
#
# 2023 × 100 × 100 × 3 × 4 byte
#
# ≈ 약 243 MB
#
#
# 따라서:
#
# x_train + x_test
#
# 만으로도 대략 1.2GB 정도의 RAM을 사용할 수 있다.
#
#
# 여기에:
#
# y_train
# y_test
# TensorFlow
# Python
# 기타 객체
#
# 등이 추가된다.
#
#
# 따라서 이 코드는:
#
# "메모리를 절약하는 코드"
#
# 라기보다는
#
# "RAM을 충분히 사용해서라도
#  전처리 결과를 한 번 만들어두고,
#  이후 로딩 속도를 높이기 위한 코드"
#
# 라고 이해하는 것이 정확하다.


# =============================================================================
# 데이터 변환 시간 출력
# =============================================================================

print(
    f"데이터 변환 시간 : "
    f"{round(time.time() - start_time, 2)} 초"
)


# start_time 이후 실행된 작업:
#
# 폴더 탐색
#       ↓
# JPG 파일 읽기
#       ↓
# JPEG 디코딩
#       ↓
# 100 x 100 resize
#       ↓
# RGB 배열 생성
#       ↓
# 0~1 rescale
#       ↓
# NumPy 배열 생성
#
#
# 이 모든 과정이 몇 초 걸렸는지 출력한다.


# =============================================================================
# 2. NPY 파일로 저장
# =============================================================================


# NPY 파일을 저장할 폴더
np_path = './_data/kaggle_cat_dog_npy/'


# 주의:
#
# np.save()는 상위 폴더를 자동으로 만들어주지 않는다.
#
# 따라서:
#
# ./_data/kaggle_cat_dog_npy/
#
# 폴더가 미리 존재해야 한다.
#
#
# 폴더가 없을 가능성이 있다면:
#
# import os
# os.makedirs(np_path, exist_ok=True)
#
# 를 추가할 수 있다.


# =============================================================================
# 학습 이미지 x_train 저장
# =============================================================================

np.save(
    np_path + 'keras45_03_x_train.npy',
    arr=x_train
)

# np.save()
#
# NumPy 배열을 .npy 형식으로 저장하는 함수
#
#
# 첫 번째 인자:
#
# 파일 경로
#
#
# 두 번째 인자:
#
# arr=x_train
#
# 저장할 NumPy 배열
#
#
# 저장되는 데이터:
#
# shape
#
# (8005, 100, 100, 3)
#
#
# 픽셀값 역시 이미:
#
# 0 ~ 1
#
# 범위로 스케일링되어 있다.


# =============================================================================
# 학습 정답 y_train 저장
# =============================================================================

np.save(
    np_path + 'keras45_03_y_train.npy',
    arr=y_train
)

# 학습 이미지 8005장에 대한 정답 저장
#
# shape:
#
# (8005,)
#
#
# 예:
#
# [0., 1., 0., 1., ...]


# =============================================================================
# 테스트 이미지 x_test 저장
# =============================================================================

np.save(
    np_path + 'keras45_03_x_test.npy',
    arr=x_test
)

# 테스트 이미지 2023장 저장
#
# shape:
#
# (2023, 100, 100, 3)


# =============================================================================
# 테스트 정답 y_test 저장
# =============================================================================

np.save(
    np_path + 'keras45_03_y_test.npy',
    arr=y_test
)

# 테스트 이미지 2023장에 대한 정답 저장
#
# shape:
#
# (2023,)


# =============================================================================
# 저장 완료
# =============================================================================

print("Cat/Dog NPY 파일 저장 완료.")


