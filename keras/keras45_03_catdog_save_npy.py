# =============================================================================
# 왜 .gitignore가 필요한가?
# =============================================================================
#
# .npy 파일은 매우 클 수 있다.
#
# 특히 x_train은 현재 거의 1GB에 가까울 수 있다.
#
# 이런 대용량 데이터 파일을 GitHub 저장소에 올리면:
#
# - Git 저장소 용량이 크게 증가
# - clone 시간이 길어짐
# - GitHub 파일 크기 제한에 걸릴 수 있음
# - 코드 버전 관리 목적과도 맞지 않음
#
#
# 따라서 일반적으로 데이터 파일은 Git에서 제외한다.
#
#
# 프로젝트의 .gitignore에 예를 들어:
#
# _data/
#
# 또는
#
# *.npy
#
# 를 작성할 수 있다.
#
#
# 차이:
#
# _data/
#
# -> _data 폴더 전체를 Git에서 제외
#
#
# *.npy
#
# -> 프로젝트 내 모든 .npy 파일을 Git에서 제외
#
#
# 데이터 전체가 Git에 올라가면 안 되는 프로젝트라면
# 보통 _data/ 자체를 제외하는 편이 관리하기 편하다.


# =============================================================================
# NPY 저장의 장점과 단점
# =============================================================================
#
# [장점]
#
# 1. JPG 디코딩을 반복하지 않아도 됨
#
# 2. resize를 반복하지 않아도 됨
#
# 3. rescale을 반복하지 않아도 됨
#
# 4. 여러 모델을 반복 실험할 때 로딩이 간단하고 빠름
#
#
# [단점]
#
# 1. 파일 용량이 커질 수 있음
#
# JPG는 압축 이미지이지만
# NPY는 픽셀 배열 자체를 저장하기 때문이다.
#
#
# 2. 전처리 결과가 고정됨
#
# 현재 저장한 데이터는:
#
# 100 x 100
# RGB
# 0~1 scaling
#
# 상태이다.
#
# 나중에:
#
